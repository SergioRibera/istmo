//! `ios/.istmo/` and the `istmo-plugins.yml` xcodegen fragment — what an
//! app's `build.rs` hands to the Xcode project.
//!
//! - `Istmo.xcconfig` carries the app identity from `[app]` (bundle id,
//!   version, build number, display name, deployment target, app icon)
//!   plus the linker settings for the Rust static library. It is the
//!   Xcode twin of what the `dev.istmo.app` Gradle plugin applies on
//!   Android, and plays the role of Flutter's `Generated.xcconfig`.
//! - `build-rust.sh` is the pre-build phase that runs cargo for every
//!   architecture Xcode builds and stages `lib<crate>.a`.
//! - `istmo-plugins.yml` (next to the app sources) wires all of the above
//!   into xcodegen projects: plugin sources, the same build settings, the
//!   pre-build phase and the generated icon catalog.
//!
//! Hand-made Xcode projects base their target configuration on
//! `Istmo.xcconfig` and add `build-rust.sh` as a Run Script phase.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::app_config::AppMetadata;
use crate::app_icon::{AppIcon, IOS_APP_ICON_SET, IconError};
use crate::emit_app::{relativise, write_if_changed};
use crate::min_versions::OsVersion;

/// Generated directory, relative to the iOS project root.
pub const IOS_GENERATED_DIR: &str = ".istmo";

const XCCONFIG_FILE: &str = "Istmo.xcconfig";
const BUILD_SCRIPT_FILE: &str = "build-rust.sh";
const ASSET_CATALOG_DIR: &str = "Assets.xcassets";
const FRAGMENT_FILE: &str = "istmo-plugins.yml";

#[derive(Debug, Clone, PartialEq, Eq)]
enum SettingValue {
    Scalar(String),
    List(Vec<String>),
}

/// The consuming app's Xcode project (`<crate>/ios/`) and its app
/// target directory.
#[derive(Debug, Clone)]
pub struct IosProject {
    root: PathBuf,
    app_dir: String,
}

impl IosProject {
    #[must_use]
    pub fn new(root: &Path, app_dir: &str) -> Self {
        Self {
            root: root.to_path_buf(),
            app_dir: app_dir.to_owned(),
        }
    }

    #[must_use]
    pub fn root(&self) -> &Path {
        &self.root
    }

    #[must_use]
    pub fn app_dir(&self) -> &str {
        &self.app_dir
    }

    /// `<root>/<app_dir>`, the app target's source directory.
    #[must_use]
    pub fn app_path(&self) -> PathBuf {
        self.root.join(&self.app_dir)
    }

    fn generated_dir(&self) -> PathBuf {
        self.root.join(IOS_GENERATED_DIR)
    }

    /// Write `Istmo.xcconfig` and `build-rust.sh`.
    pub fn write_generated(&self, app: &AppMetadata) {
        let dir = self.generated_dir();
        write_if_changed(&dir.join(XCCONFIG_FILE), &render_xcconfig(app));
        let script = dir.join(BUILD_SCRIPT_FILE);
        let crate_dir = relativise(&dir, &app.krate.manifest_dir)
            .unwrap_or_else(|| app.krate.manifest_dir.display().to_string());
        write_if_changed(&script, &render_build_script(app, &crate_dir));
        make_executable(&script);
    }

    /// Write the `IstmoAppIcon` asset catalog.
    pub fn write_icon(&self, icon: &AppIcon) -> Result<(), IconError> {
        icon.write_ios_app_icon_set(&self.generated_dir().join(ASSET_CATALOG_DIR))
    }

    /// Write `<app_dir>/istmo-plugins.yml`.
    ///
    /// `plugin_dirs` are the linked plugins' `native/ios/` directories;
    /// `plugin_min_ios` the strictest plugin `[min_versions] ios` with
    /// the plugin that requires it, checked again from Xcode.
    pub fn write_xcodegen_fragment(
        &self,
        app: &AppMetadata,
        plugin_dirs: &[(String, PathBuf)],
        plugin_min_ios: Option<&(OsVersion, String)>,
    ) {
        let fragment_dir = self.app_path();
        let relative = |target: &Path| {
            relativise(&fragment_dir, target).unwrap_or_else(|| target.display().to_string())
        };
        let app_dir = &self.app_dir;
        let mut yaml = String::new();
        yaml.push_str("# GENERATED by istmo-build — DO NOT EDIT.\n");
        yaml.push_str("# Include this file from your app's `project.yml`:\n");
        yaml.push_str("#   include:\n");
        writeln!(yaml, "#     - path: {app_dir}/{FRAGMENT_FILE}").ok();
        yaml.push_str("# xcodegen merges the entries below into your app target; values set\n");
        yaml.push_str("# in project.yml take precedence over the ones here.\n");
        yaml.push_str("targets:\n");
        writeln!(yaml, "  {app_dir}:").ok();

        let icon_catalog = app
            .icon
            .as_ref()
            .map(|_| relative(&self.generated_dir().join(ASSET_CATALOG_DIR)));
        if !plugin_dirs.is_empty() || icon_catalog.is_some() {
            yaml.push_str("    sources:\n");
        }
        for (name, dir) in plugin_dirs {
            // xcodegen resolves `path:` relative to the file declaring it;
            // a relative path keeps the fragment portable across machines.
            writeln!(yaml, "      - path: {}", yaml_string(&relative(dir))).ok();
            writeln!(yaml, "        name: {name}").ok();
            yaml.push_str("        type: group\n");
            yaml.push_str("        createIntermediateGroups: true\n");
            yaml.push_str("        excludes:\n");
            yaml.push_str("          - \"*.fragment\"\n");
        }
        if let Some(catalog) = icon_catalog {
            writeln!(yaml, "      - path: {}", yaml_string(&catalog)).ok();
        }

        yaml.push_str("    settings:\n");
        yaml.push_str("      base:\n");
        for (key, value) in build_settings(app) {
            match value {
                SettingValue::Scalar(v) => {
                    writeln!(yaml, "        {key}: {}", yaml_string(&v)).ok();
                }
                SettingValue::List(items) => {
                    writeln!(yaml, "        {key}:").ok();
                    for item in items {
                        writeln!(yaml, "          - {}", yaml_string(&item)).ok();
                    }
                }
            }
        }

        yaml.push_str("    preBuildScripts:\n");
        if let Some((min, plugin)) = plugin_min_ios {
            yaml.push_str("      - name: istmo minimum iOS version\n");
            yaml.push_str("        basedOnDependencyAnalysis: false\n");
            yaml.push_str("        script: |\n");
            writeln!(yaml, "          required=\"{min}\"").ok();
            yaml.push_str("          actual=\"${IPHONEOS_DEPLOYMENT_TARGET:-0}\"\n");
            yaml.push_str(
                "          lowest=$(printf '%s\\n%s\\n' \"$required\" \"$actual\" | sort -t. -k1,1n -k2,2n -k3,3n | head -n1)\n",
            );
            yaml.push_str("          if [ \"$lowest\" != \"$required\" ]; then\n");
            writeln!(
                yaml,
                "            echo \"error: istmo plugin {plugin} requires iOS >= $required, but IPHONEOS_DEPLOYMENT_TARGET is $actual\""
            )
            .ok();
            yaml.push_str("            exit 1\n");
            yaml.push_str("          fi\n");
        }
        yaml.push_str("      - name: istmo cargo build\n");
        yaml.push_str("        basedOnDependencyAnalysis: false\n");
        writeln!(
            yaml,
            "        script: '\"${{PROJECT_DIR}}/{IOS_GENERATED_DIR}/{BUILD_SCRIPT_FILE}\"'"
        )
        .ok();

        write_if_changed(&fragment_dir.join(FRAGMENT_FILE), &yaml);
    }
}

/// `CFBundleShortVersionString` must be up to three dot-separated
/// integers: drop any `SemVer` pre-release / build suffix.
fn marketing_version(version: &str) -> &str {
    version.split(['-', '+']).next().unwrap_or(version)
}

fn build_settings(app: &AppMetadata) -> Vec<(&'static str, SettingValue)> {
    let lib = &app.krate.lib_name;
    let mut settings = vec![
        ("ISTMO_LIB_NAME", SettingValue::Scalar(lib.clone())),
        (
            "LIBRARY_SEARCH_PATHS",
            SettingValue::List(vec![
                "$(inherited)".to_owned(),
                "$(PROJECT_DIR)/build/rust/$(PLATFORM_NAME)/$(CURRENT_ARCH)".to_owned(),
            ]),
        ),
        (
            "OTHER_LDFLAGS",
            SettingValue::List(vec!["$(inherited)".to_owned(), format!("-l{lib}")]),
        ),
        // The cargo pre-build phase writes outside the declared outputs.
        (
            "ENABLE_USER_SCRIPT_SANDBOXING",
            SettingValue::Scalar("NO".to_owned()),
        ),
        (
            "MARKETING_VERSION",
            SettingValue::Scalar(marketing_version(&app.version).to_owned()),
        ),
        (
            "CURRENT_PROJECT_VERSION",
            SettingValue::Scalar(app.build.to_string()),
        ),
        ("ISTMO_DISPLAY_NAME", SettingValue::Scalar(app.name.clone())),
    ];
    if let Some(id) = &app.id {
        settings.push((
            "PRODUCT_BUNDLE_IDENTIFIER",
            SettingValue::Scalar(id.to_string()),
        ));
    }
    if let Some(min) = app.min_ios {
        settings.push((
            "IPHONEOS_DEPLOYMENT_TARGET",
            SettingValue::Scalar(min.to_string()),
        ));
    }
    if app.icon.is_some() {
        settings.push((
            "ASSETCATALOG_COMPILER_APPICON_NAME",
            SettingValue::Scalar(IOS_APP_ICON_SET.to_owned()),
        ));
    }
    settings
}

fn render_xcconfig(app: &AppMetadata) -> String {
    let mut out = String::from(
        "// GENERATED by istmo-build — DO NOT EDIT.\n\
         // App identity from istmo.toml `[app]` and the Rust library link\n\
         // settings. Base your app target's configuration on this file, and\n\
         // reference $(MARKETING_VERSION), $(CURRENT_PROJECT_VERSION) and\n\
         // $(ISTMO_DISPLAY_NAME) from Info.plist.\n",
    );
    for (key, value) in build_settings(app) {
        let rendered = match value {
            SettingValue::Scalar(v) => v,
            SettingValue::List(items) => items.join(" "),
        };
        writeln!(out, "{key} = {rendered}").ok();
    }
    out
}

fn render_build_script(app: &AppMetadata, crate_dir: &str) -> String {
    let package = &app.krate.package;
    let lib = &app.krate.lib_name;
    format!(
        r#"#!/bin/bash
# GENERATED by istmo-build — DO NOT EDIT.
# Xcode pre-build phase: compiles the Rust static library for every
# architecture Xcode builds and stages it where LIBRARY_SEARCH_PATHS
# expects it.
set -euo pipefail

PACKAGE="{package}"
LIB_NAME="{lib}"
SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
MANIFEST_PATH="${{SCRIPT_DIR}}/{crate_dir}/Cargo.toml"

: "${{PLATFORM_NAME:=iphonesimulator}}"
: "${{ARCHS:=arm64}}"
: "${{CONFIGURATION:=Debug}}"
: "${{PROJECT_DIR:=$(cd "${{SCRIPT_DIR}}/.." && pwd)}}"

# Xcode launched from Finder or the Dock does not inherit the shell PATH.
export PATH="${{CARGO_HOME:-$HOME/.cargo}}/bin:${{PATH}}"

if ! command -v cargo >/dev/null 2>&1; then
    echo "error: istmo: cargo not found. Install Rust from https://rustup.rs (or set CARGO_HOME)."
    exit 1
fi

installed_targets=""
if command -v rustup >/dev/null 2>&1; then
    installed_targets="$(rustup target list --installed)"
fi

profile_flag=""
if [[ "${{CONFIGURATION}}" == "Release" ]]; then
    profile_flag="--release"
fi

for arch in ${{ARCHS}}; do
    case "${{PLATFORM_NAME}}-${{arch}}" in
        iphoneos-arm64)         triple="aarch64-apple-ios" ;;
        iphonesimulator-arm64)  triple="aarch64-apple-ios-sim" ;;
        iphonesimulator-x86_64) triple="x86_64-apple-ios" ;;
        *)
            echo "error: istmo: unsupported platform/architecture ${{PLATFORM_NAME}}/${{arch}}"
            exit 1
            ;;
    esac

    if [[ -n "${{installed_targets}}" ]] && ! grep -qx "${{triple}}" <<<"${{installed_targets}}"; then
        echo "error: istmo: the Rust target ${{triple}} is not installed. Run: rustup target add ${{triple}}"
        exit 1
    fi

    artifact="$(cargo build \
        --manifest-path "${{MANIFEST_PATH}}" \
        -p "${{PACKAGE}}" --lib \
        --target "${{triple}}" \
        ${{profile_flag}} \
        --message-format=json-render-diagnostics \
        | {{ grep -o "\"[^\"]*/lib${{LIB_NAME}}\.a\"" || true; }} \
        | tail -n 1 | tr -d '"')"
    if [[ -z "${{artifact}}" ]]; then
        echo "error: istmo: cargo produced no lib${{LIB_NAME}}.a; add \"staticlib\" to [lib] crate-type in Cargo.toml."
        exit 1
    fi

    dst_dir="${{PROJECT_DIR}}/build/rust/${{PLATFORM_NAME}}/${{arch}}"
    mkdir -p "${{dst_dir}}"
    cp "${{artifact}}" "${{dst_dir}}/lib${{LIB_NAME}}.a"
done
"#
    )
}

fn yaml_string(raw: &str) -> String {
    format!("\"{}\"", raw.replace('\\', "\\\\").replace('"', "\\\""))
}

#[cfg(unix)]
fn make_executable(path: &Path) {
    use std::os::unix::fs::PermissionsExt;
    if let Ok(meta) = std::fs::metadata(path) {
        let mut perms = meta.permissions();
        if perms.mode() & 0o111 != 0o111 {
            perms.set_mode(perms.mode() | 0o755);
            let _ = std::fs::set_permissions(path, perms);
        }
    }
}

#[cfg(not(unix))]
const fn make_executable(_path: &Path) {}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::app_config::{AppId, AppIdentity, CrateInfo};
    use crate::min_versions::MinVersions;

    fn app(icon: bool) -> AppMetadata {
        AppMetadata::resolve(
            &AppIdentity {
                id: Some(AppId::try_from("dev.istmo.demo").unwrap()),
                name: Some("Demo \"App\"".into()),
                build: Some(12),
                icon: icon.then(|| PathBuf::from("icon.png")),
                ..AppIdentity::default()
            },
            &MinVersions {
                ios: Some(OsVersion::new(15, 0, 0)),
                ..MinVersions::default()
            },
            CrateInfo {
                package: "demo-app".into(),
                version: "0.2.0-alpha.1".into(),
                lib_name: "demo_app".into(),
                crate_types: vec!["staticlib".into()],
                manifest_dir: PathBuf::from("/work/demo-app"),
            },
        )
    }

    #[test]
    fn marketing_version_drops_prerelease() {
        assert_eq!(marketing_version("1.2.3"), "1.2.3");
        assert_eq!(marketing_version("0.2.0-alpha.1"), "0.2.0");
        assert_eq!(marketing_version("1.0.0+build5"), "1.0.0");
    }

    #[test]
    fn xcconfig_carries_identity_and_link_settings() {
        let xcconfig = render_xcconfig(&app(true));
        for line in [
            "ISTMO_LIB_NAME = demo_app",
            "LIBRARY_SEARCH_PATHS = $(inherited) $(PROJECT_DIR)/build/rust/$(PLATFORM_NAME)/$(CURRENT_ARCH)",
            "OTHER_LDFLAGS = $(inherited) -ldemo_app",
            "MARKETING_VERSION = 0.2.0",
            "CURRENT_PROJECT_VERSION = 12",
            "PRODUCT_BUNDLE_IDENTIFIER = dev.istmo.demo",
            "IPHONEOS_DEPLOYMENT_TARGET = 15.0",
            "ASSETCATALOG_COMPILER_APPICON_NAME = IstmoAppIcon",
        ] {
            assert!(xcconfig.contains(line), "missing `{line}` in:\n{xcconfig}");
        }
    }

    #[test]
    fn xcconfig_omits_icon_without_app_icon() {
        assert!(!render_xcconfig(&app(false)).contains("ASSETCATALOG_COMPILER_APPICON_NAME"));
    }

    #[test]
    fn build_script_bakes_package_and_relative_crate_dir() {
        let script = render_build_script(&app(false), "../..");
        assert!(script.starts_with("#!/bin/bash\n"));
        assert!(script.contains("PACKAGE=\"demo-app\""));
        assert!(script.contains("LIB_NAME=\"demo_app\""));
        assert!(script.contains("MANIFEST_PATH=\"${SCRIPT_DIR}/../../Cargo.toml\""));
        assert!(script.contains("rustup target add ${triple}"));
    }

    #[test]
    fn yaml_strings_are_escaped() {
        assert_eq!(yaml_string("Demo \"App\""), "\"Demo \\\"App\\\"\"");
        assert_eq!(yaml_string("$(inherited)"), "\"$(inherited)\"");
    }
}
