//! Resources linked into a Windows executable: the `[app.icon]` desktop
//! icon and the application manifest composed from every
//! `[[windows_manifest_fragment]]` the app and its plugins declare.
//!
//! The icon always travels in a compiled `.rc` (via `embed-resource`,
//! which finds `rc.exe`, `llvm-rc` or `windres`). The manifest goes
//! through the `.rc` only on GNU targets; MSVC's linker embeds its own
//! default manifest, so there it is handed over with
//! `/MANIFEST:EMBED /MANIFESTINPUT:` instead of clashing with a second
//! `RT_MANIFEST` resource.

use std::collections::BTreeMap;
use std::fmt::{self, Write as _};
use std::fs;
use std::path::{Path, PathBuf};

use crate::app_icon::{AppIcon, IconError};
use crate::manifest::WindowsManifestFragment;

const ICON_FILE: &str = "istmo-app.ico";
const MANIFEST_FILE: &str = "istmo-app.manifest";
const RESOURCE_FILE: &str = "istmo-app.rc";

#[derive(Debug)]
pub enum WindowsResourceError {
    Icon(IconError),
    Write {
        path: PathBuf,
        source: std::io::Error,
    },
    Compile(embed_resource::CompilationResult),
}

impl fmt::Display for WindowsResourceError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Icon(source) => write!(f, "Windows icon: {source}"),
            Self::Write { path, source } => write!(f, "writing {}: {source}", path.display()),
            Self::Compile(result) => write!(f, "compiling {RESOURCE_FILE}: {result}"),
        }
    }
}

impl std::error::Error for WindowsResourceError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Icon(source) => Some(source),
            Self::Write { source, .. } => Some(source),
            Self::Compile(result) => Some(result),
        }
    }
}

impl From<IconError> for WindowsResourceError {
    fn from(source: IconError) -> Self {
        Self::Icon(source)
    }
}

/// Which linker the Windows target uses, from `CARGO_CFG_TARGET_ENV`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WindowsToolchain {
    Msvc,
    Gnu,
}

impl From<&str> for WindowsToolchain {
    fn from(target_env: &str) -> Self {
        if target_env == "msvc" {
            Self::Msvc
        } else {
            Self::Gnu
        }
    }
}

/// What the app's Windows executable gets linked with.
#[derive(Debug)]
pub struct WindowsResources<'a> {
    pub icon: Option<&'a AppIcon>,
    /// Composed `App.exe.manifest`, when any fragment is declared.
    pub manifest: Option<String>,
}

impl WindowsResources<'_> {
    /// Write the resources under `out_dir`, compile and link them.
    /// Does nothing when there is neither an icon nor a manifest.
    pub fn emit(
        &self,
        out_dir: &Path,
        toolchain: WindowsToolchain,
    ) -> Result<(), WindowsResourceError> {
        let mut rc = String::new();
        if let Some(icon) = self.icon {
            let path = out_dir.join(ICON_FILE);
            icon.write_ico(&path)?;
            let _ = writeln!(rc, "1 ICON \"{}\"", rc_path(&path));
        }
        if let Some(manifest) = &self.manifest {
            let path = out_dir.join(MANIFEST_FILE);
            write(&path, manifest)?;
            match toolchain {
                WindowsToolchain::Msvc => {
                    println!("cargo::rustc-link-arg-bins=/MANIFEST:EMBED");
                    println!(
                        "cargo::rustc-link-arg-bins=/MANIFESTINPUT:{}",
                        path.display()
                    );
                }
                WindowsToolchain::Gnu => {
                    let _ = writeln!(rc, "1 24 \"{}\"", rc_path(&path));
                }
            }
        }
        if rc.is_empty() {
            return Ok(());
        }
        let path = out_dir.join(RESOURCE_FILE);
        write(&path, &rc)?;
        embed_resource::compile(&path, embed_resource::NONE)
            .manifest_required()
            .map_err(WindowsResourceError::Compile)
    }
}

/// Compose an application manifest from `fragments`: one per `name`
/// (the first declaration wins), sorted by name so the output is
/// stable. Each fragment's `xml` is a direct child of `<assembly>`.
#[must_use]
pub fn compose_manifest<'a>(
    fragments: impl IntoIterator<Item = &'a WindowsManifestFragment>,
) -> Option<String> {
    let mut unique = BTreeMap::new();
    for fragment in fragments {
        unique
            .entry(fragment.name.as_str())
            .or_insert_with(|| fragment.xml.trim());
    }
    if unique.is_empty() {
        return None;
    }
    let mut xml = String::from(
        "<?xml version=\"1.0\" encoding=\"UTF-8\" standalone=\"yes\"?>\n\
         <!-- Generated by istmo-build from [[windows_manifest_fragment]]. -->\n\
         <assembly xmlns=\"urn:schemas-microsoft-com:asm.v1\" manifestVersion=\"1.0\">\n",
    );
    for fragment in unique.values() {
        xml.push_str(fragment);
        xml.push('\n');
    }
    xml.push_str("</assembly>\n");
    Some(xml)
}

/// `.rc` string literal for `path`: backslashes must be doubled.
fn rc_path(path: &Path) -> String {
    path.display().to_string().replace('\\', "\\\\")
}

fn write(path: &Path, contents: &str) -> Result<(), WindowsResourceError> {
    if fs::read_to_string(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    fs::write(path, contents).map_err(|source| WindowsResourceError::Write {
        path: path.to_path_buf(),
        source,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn fragment(name: &str, xml: &str) -> WindowsManifestFragment {
        WindowsManifestFragment {
            name: name.to_owned(),
            xml: xml.to_owned(),
        }
    }

    #[test]
    fn no_fragments_no_manifest() {
        assert!(compose_manifest(&[]).is_none());
    }

    #[test]
    fn composes_unique_sorted_fragments() {
        let fragments = [
            fragment("dpi", "<application>dpi</application>"),
            fragment("controls", "  <dependency>controls</dependency>\n"),
            fragment("dpi", "<application>ignored</application>"),
        ];
        let xml = compose_manifest(&fragments).unwrap();
        let controls = xml.find("<dependency>controls</dependency>").unwrap();
        let dpi = xml.find("<application>dpi</application>").unwrap();
        assert!(controls < dpi);
        assert!(!xml.contains("ignored"));
        assert!(xml.starts_with("<?xml"));
        assert!(xml.trim_end().ends_with("</assembly>"));
    }

    #[test]
    fn rc_paths_escape_backslashes() {
        assert_eq!(
            rc_path(Path::new(r"C:\out\istmo-app.ico")),
            r"C:\\out\\istmo-app.ico"
        );
    }

    #[test]
    fn toolchain_from_target_env() {
        assert_eq!(WindowsToolchain::from("msvc"), WindowsToolchain::Msvc);
        assert_eq!(WindowsToolchain::from("gnu"), WindowsToolchain::Gnu);
    }
}
