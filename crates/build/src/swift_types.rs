use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::codegen::{
    NamedAccess, SwiftNames, SwiftWire, local, swift_ident, swift_label, write_header,
};
use crate::contract::{Contract, EnumDef, SharedTypes, StructDef, TypeDef, TypeRef};

/// Locals a struct reader declares before decoding its fields.
const READER_LOCALS: &[&str] = &["c"];

#[must_use]
pub fn generate_swift_types(contract: &Contract) -> String {
    let errors = error_type_names(contract);
    let mut out = String::new();
    write_header(&mut out, contract);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    if contract.references_native_handle() {
        // `NativeHandleId` is declared by the runtime module.
        let _ = writeln!(out, "import IstmoRuntime");
    }
    let names = SwiftNames::of(contract).within();
    write_namespace(
        &mut out,
        names,
        &format!("The `{}` plugin's message types.", contract.type_name),
        contract.types.iter().map(|ty| {
            let is_error = is_error_shape(ty.name()) || errors.contains(ty.name());
            (ty, is_error)
        }),
    );
    out
}

/// The declarations of a shared group's types, one Swift file per group,
/// nested in the group's namespace. No codecs: every plugin's
/// `CodecsImpl` reads and writes the shared types it uses.
#[must_use]
pub fn generate_swift_shared_types(group: &SharedTypes) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// shared types: {}", group.group);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    let mut handles = false;
    for ty in &group.types {
        let refs: Vec<&TypeRef> = match ty {
            TypeDef::Struct(s) => s.fields.iter().map(|f| &f.ty).collect(),
            TypeDef::Enum(e) => e.variants.iter().flat_map(|v| v.payload.iter()).collect(),
        };
        for r in refs {
            r.for_each_named(&mut |name| handles |= name == crate::codegen::NATIVE_HANDLE_ID);
        }
    }
    if handles {
        let _ = writeln!(out, "import IstmoRuntime");
    }
    write_namespace(
        &mut out,
        SwiftNames::of_group(group),
        &format!("Message types shared by plugins: `{}`.", group.group),
        group.types.iter().map(|ty| (ty, is_error_shape(ty.name()))),
    );
    out
}

/// `public enum <Namespace> {}` and an extension nesting each type in it.
fn write_namespace<'a>(
    out: &mut String,
    names: SwiftNames<'_>,
    doc: &str,
    types: impl Iterator<Item = (&'a TypeDef, bool)>,
) {
    let namespace = names.namespace();
    let _ = writeln!(out);
    let _ = writeln!(out, "/// {doc}");
    let _ = writeln!(out, "public enum {namespace} {{}}");
    let mut body = String::new();
    for (ty, is_error) in types {
        if !body.is_empty() {
            body.push('\n');
        }
        match ty {
            TypeDef::Struct(s) => write_struct(&mut body, names, s, is_error),
            TypeDef::Enum(e) => write_enum(&mut body, names, e, is_error),
        }
    }
    if body.is_empty() {
        return;
    }
    let _ = writeln!(out);
    let _ = writeln!(out, "extension {namespace} {{");
    for line in body.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "    {line}");
        }
    }
    let _ = writeln!(out, "}}");
}

#[must_use]
pub fn generate_swift_codecs(contract: &Contract) -> String {
    let names = SwiftNames::of(contract);
    let wire = SwiftWire::new(NamedAccess::SelfImpl, names);
    let mut out = String::new();
    write_header(&mut out, contract);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out, "import IstmoRuntime");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "public final class {}CodecsImpl: {}Codecs {{",
        contract.type_name, contract.type_name,
    );
    let _ = writeln!(out, "    public init() {{}}");
    for ty in contract.codec_types() {
        let _ = writeln!(out);
        match ty {
            TypeDef::Struct(s) => write_struct_codec(&mut out, wire, names, s),
            TypeDef::Enum(e) => write_enum_codec(&mut out, wire, names, e),
        }
    }
    if contract.references_native_handle() {
        let _ = writeln!(out);
        write_native_handle_codec(&mut out);
    }
    let _ = writeln!(out, "}}");
    out
}

/// Module-scope names generated Swift spells unqualified (runtime,
/// standard library, app-wide generated symbols): a namespace with one of
/// these names would shadow it everywhere, a message type inside its own
/// namespace.
const RESERVED_NAMES: &[&str] = &[
    "AsyncThrowingStream",
    "Bincode",
    "Bool",
    "Data",
    "Double",
    "Error",
    "Float",
    "Foundation",
    "HandleReleaser",
    "Int16",
    "Int32",
    "Int64",
    "Int8",
    "IstmoApp",
    "IstmoFrameSender",
    "IstmoPluginRegistry",
    "IstmoRuntime",
    "IstmoRuntimeError",
    "NSLock",
    "NativeHandleId",
    "PluginException",
    "PluginHandler",
    "PluginResult",
    "PluginRuntimeError",
    "Sendable",
    "String",
    "Swift",
    "UInt16",
    "UInt32",
    "UInt64",
    "UInt8",
    "Void",
];

/// Top-level Swift symbols generated for `contract`: its namespace, the
/// classes and protocols around it and its exceptions.
fn top_level_symbols(contract: &Contract) -> Vec<String> {
    let ty = &contract.type_name;
    let mut out = vec![ty.clone()];
    out.extend(
        ["Backend", "Client", "Codecs", "CodecsImpl", "Dispatcher"]
            .iter()
            .map(|suffix| format!("{ty}{suffix}")),
    );
    if contract.init.is_some() {
        out.push(format!("{ty}Factory"));
    }
    out.extend(
        contract
            .error_types()
            .into_iter()
            .map(|err| contract.exception_name(err)),
    );
    out
}

/// Checks that the Swift one app generates for `contracts` cannot clash.
///
/// Plugin namespaces, shared group namespaces and the symbols generated
/// around each plugin must be distinct and must not shadow a name the
/// generated code relies on; no message type may be named like a name
/// spelled unqualified inside its namespace.
///
/// # Errors
/// The first clash, naming both sides and what to rename.
pub fn check_swift_namespaces(contracts: &[&Contract]) -> Result<(), String> {
    const RUNTIME: &str = "the istmo runtime or the Swift standard library";
    let mut owners: BTreeMap<String, String> = RESERVED_NAMES
        .iter()
        .map(|name| ((*name).to_owned(), RUNTIME.to_owned()))
        .collect();
    let mut declare = |name: String, owner: String| -> Result<(), String> {
        match owners.get(&name) {
            Some(existing) if *existing == owner => Ok(()),
            Some(existing) => Err(format!(
                "Swift name `{name}` is declared by {owner} and by {existing}: \
                 rename the plugin trait or the shared group"
            )),
            None => {
                owners.insert(name, owner);
                Ok(())
            }
        }
    };
    for contract in contracts {
        let owner = format!("plugin `{}`", contract.plugin_id);
        for symbol in top_level_symbols(contract) {
            declare(symbol, owner.clone())?;
        }
    }
    for group in contracts.iter().flat_map(|c| c.shared.iter()) {
        declare(
            group.group.clone(),
            format!("shared types `{}`", group.group),
        )?;
    }
    for contract in contracts {
        let groups: Vec<&str> = contract.shared.iter().map(|g| g.group.as_str()).collect();
        let nested = contract
            .types
            .iter()
            .map(|ty| (contract.type_name.as_str(), ty))
            .chain(
                contract
                    .shared
                    .iter()
                    .flat_map(|g| g.types.iter().map(move |ty| (g.group.as_str(), ty))),
            );
        for (namespace, ty) in nested {
            let name = ty.name();
            if RESERVED_NAMES.contains(&name) || groups.contains(&name) {
                return Err(format!(
                    "message type `{namespace}.{name}` (plugin `{}`) shadows `{name}` inside \
                     its Swift namespace: rename the type",
                    contract.plugin_id
                ));
            }
        }
    }
    Ok(())
}

/// Declared types some method throws: they must conform to `Error` for
/// the dispatcher's `catch let err as T` and the client's `throw`.
fn error_type_names(contract: &Contract) -> BTreeSet<&str> {
    contract
        .error_types()
        .into_iter()
        .filter_map(|ty| match ty {
            TypeRef::Named(name) => Some(name.as_str()),
            _ => None,
        })
        .collect()
}

fn write_struct(out: &mut String, names: SwiftNames<'_>, s: &StructDef, is_error: bool) {
    // `Error` refines `Sendable`; plain types state it, so backends can
    // capture them in `@Sendable` capture callbacks (Swift 6 mode).
    let conform = if is_error { ": Error" } else { ": Sendable" };
    let _ = writeln!(out, "public struct {}{conform} {{", s.name);
    for f in &s.fields {
        let _ = writeln!(
            out,
            "    public let {}: {}",
            swift_ident(&f.name),
            names.ty(&f.ty)
        );
    }
    let _ = writeln!(out);
    let init_args = s
        .fields
        .iter()
        .map(|f| format!("{}: {}", swift_ident(&f.name), names.ty(&f.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(out, "    public init({init_args}) {{");
    for f in &s.fields {
        let name = swift_ident(&f.name);
        let _ = writeln!(out, "        self.{name} = {name}");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
}

fn write_enum(out: &mut String, names: SwiftNames<'_>, e: &EnumDef, is_error: bool) {
    if e.is_plain() {
        let conform = if is_error { ", Error" } else { ", Sendable" };
        let _ = writeln!(out, "public enum {}: UInt32{conform} {{", e.name);
        for (i, v) in e.variants.iter().enumerate() {
            let _ = writeln!(out, "    case {} = {i}", to_swift_case(&v.name));
        }
    } else {
        // Unit cases plus `.unknown` keep the `Hashable` a raw-value enum
        // has.
        let hashable = if e.has_payload() { "" } else { "Hashable, " };
        let conform = if is_error { "Error" } else { "Sendable" };
        let _ = writeln!(out, "public enum {}: {hashable}{conform} {{", e.name);
        for v in &e.variants {
            let case_name = to_swift_case(&v.name);
            if v.payload.is_empty() {
                let _ = writeln!(out, "    case {case_name}");
            } else {
                let tys = v
                    .payload
                    .iter()
                    .map(|ty| names.ty(ty))
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(out, "    case {case_name}({tys})");
            }
        }
        if e.non_exhaustive {
            let _ = writeln!(
                out,
                "    /// A case added after this code was generated: its discriminant and the"
            );
            let _ = writeln!(
                out,
                "    /// rest of the message after it, written back as they came."
            );
            let _ = writeln!(out, "    case unknown(discriminant: UInt32, payload: Data)");
        }
    }
    let _ = writeln!(out, "}}");
}

fn is_error_shape(name: &str) -> bool {
    name.ends_with("Error")
}

/// Swift case names are lowerCamelCase.
fn to_swift_case(name: &str) -> String {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return String::new();
    };
    let base = first.to_lowercase().collect::<String>() + chars.as_str();
    swift_ident(&base)
}

fn write_struct_codec(out: &mut String, wire: SwiftWire<'_>, names: SwiftNames<'_>, s: &StructDef) {
    let ty = names.named(&s.name);
    let _ = writeln!(
        out,
        "    public func read{}(_ c: inout Bincode.Cursor) throws -> {} {{",
        s.name, ty,
    );
    let mut init_args = Vec::with_capacity(s.fields.len());
    for f in &s.fields {
        let label = swift_label(&f.name);
        // A `()` field occupies no wire bytes; binding it to a local
        // draws swiftc's "inferred to have type '()'" warning.
        if f.ty.is_unit() {
            init_args.push(format!("{label}: ()"));
            continue;
        }
        let name = local(&f.name, READER_LOCALS, swift_ident);
        let _ = writeln!(out, "        let {name} = {}", wire.read(&f.ty, "c"));
        init_args.push(format!("{label}: {name}"));
    }
    let _ = writeln!(out, "        return {ty}({})", init_args.join(", "));
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "    public func write{}(_ out: inout Data, _ value: {}) {{",
        s.name, ty,
    );
    for f in &s.fields {
        let value = format!("value.{}", swift_ident(&f.name));
        wire.write_stmt(out, "        ", &f.ty, "out", &value);
    }
    let _ = writeln!(out, "    }}");
}

fn write_enum_codec(out: &mut String, wire: SwiftWire<'_>, names: SwiftNames<'_>, e: &EnumDef) {
    let ty = names.named(&e.name);
    let cases = !e.is_plain();

    let _ = writeln!(
        out,
        "    public func read{}(_ c: inout Bincode.Cursor) throws -> {} {{",
        e.name, ty,
    );
    let _ = writeln!(out, "        let disc = try Bincode.readVarintU32(&c)");
    if cases {
        let _ = writeln!(out, "        switch disc {{");
        for (i, v) in e.variants.iter().enumerate() {
            let case_name = to_swift_case(&v.name);
            match v.payload.as_slice() {
                [] => {
                    let _ = writeln!(out, "        case {i}: return .{case_name}");
                }
                [ty] => {
                    let _ = writeln!(
                        out,
                        "        case {i}: return .{case_name}({})",
                        wire.read(ty, "c")
                    );
                }
                payload => {
                    let _ = writeln!(out, "        case {i}:");
                    let mut bindings = Vec::with_capacity(payload.len());
                    for (idx, ty) in payload.iter().enumerate() {
                        let name = format!("f{idx}");
                        let _ = writeln!(out, "            let {name} = {}", wire.read(ty, "c"));
                        bindings.push(name);
                    }
                    let _ = writeln!(
                        out,
                        "            return .{case_name}({})",
                        bindings.join(", ")
                    );
                }
            }
        }
        if e.non_exhaustive {
            // The payload's shape is unknown, so the case keeps the rest
            // of the message: a value read after it fails to decode
            // instead of reading the payload's bytes.
            let _ = writeln!(out, "        default:");
            let _ = writeln!(
                out,
                "            let payload = c.data.subdata(in: (c.data.endIndex - c.remaining) ..< c.data.endIndex)"
            );
            let _ = writeln!(out, "            c.offset += payload.count");
            let _ = writeln!(
                out,
                "            return .unknown(discriminant: disc, payload: payload)"
            );
        } else {
            let _ = writeln!(
                out,
                "        default: throw Bincode.DecodeError.invalidTag(UInt8(clamping: disc))",
            );
        }
        let _ = writeln!(out, "        }}");
    } else {
        let _ = writeln!(
            out,
            "        guard let value = {ty}(rawValue: disc) else {{",
        );
        let _ = writeln!(
            out,
            "            throw Bincode.DecodeError.invalidTag(UInt8(clamping: disc))",
        );
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "        return value");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    write_enum_writer(out, wire, e, &ty, cases);
}

fn write_enum_writer(out: &mut String, wire: SwiftWire<'_>, e: &EnumDef, ty: &str, cases: bool) {
    let _ = writeln!(
        out,
        "    public func write{}(_ out: inout Data, _ value: {}) {{",
        e.name, ty,
    );
    if cases {
        let _ = writeln!(out, "        switch value {{");
        for (i, v) in e.variants.iter().enumerate() {
            let case_name = to_swift_case(&v.name);
            match v.payload.as_slice() {
                [] => {
                    let _ = writeln!(out, "        case .{case_name}:");
                    let _ = writeln!(out, "            Bincode.writeVarintU32(&out, {i})");
                }
                [ty] => {
                    let _ = writeln!(out, "        case .{case_name}(let payload):");
                    let _ = writeln!(out, "            Bincode.writeVarintU32(&out, {i})");
                    wire.write_stmt(out, "            ", ty, "out", "payload");
                }
                payload => {
                    let bindings = (0..payload.len())
                        .map(|idx| format!("let f{idx}"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let _ = writeln!(out, "        case .{case_name}({bindings}):");
                    let _ = writeln!(out, "            Bincode.writeVarintU32(&out, {i})");
                    for (idx, ty) in payload.iter().enumerate() {
                        wire.write_stmt(out, "            ", ty, "out", &format!("f{idx}"));
                    }
                }
            }
        }
        if e.non_exhaustive {
            let _ = writeln!(out, "        case .unknown(let discriminant, let payload):");
            let _ = writeln!(
                out,
                "            Bincode.writeVarintU32(&out, discriminant)"
            );
            let _ = writeln!(out, "            out.append(payload)");
        }
        let _ = writeln!(out, "        }}");
    } else {
        let _ = writeln!(out, "        Bincode.writeVarintU32(&out, value.rawValue)");
    }
    let _ = writeln!(out, "    }}");
}

fn write_native_handle_codec(out: &mut String) {
    let _ = writeln!(
        out,
        "    public func readNativeHandleId(_ c: inout Bincode.Cursor) throws -> NativeHandleId {{",
    );
    let _ = writeln!(out, "        return try Bincode.readVarintU64(&c)");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    public func writeNativeHandleId(_ out: inout Data, _ value: NativeHandleId) {{",
    );
    let _ = writeln!(out, "        Bincode.writeVarintU64(&out, value)");
    let _ = writeln!(out, "    }}");
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::contract::{Method, MethodKind};

    fn unit_enum(name: &str) -> TypeDef {
        TypeDef::Enum(EnumDef {
            non_exhaustive: false,
            name: name.to_owned(),
            variants: Vec::new(),
        })
    }

    fn media() -> SharedTypes {
        SharedTypes {
            group: "IstmoMedia".to_owned(),
            kotlin_package: "dev.istmo.media".to_owned(),
            types: vec![unit_enum("AccessStatus")],
        }
    }

    fn contract(type_name: &str, types: &[&str]) -> Contract {
        Contract {
            plugin_id: format!("test.{}", type_name.to_lowercase()),
            type_name: type_name.to_owned(),
            methods: vec![Method {
                name: "fail".to_owned(),
                kind: MethodKind::Unary,
                args: Vec::new(),
                returns: TypeRef::Unit,
                error: Some(TypeRef::Named(format!("{type_name}Error"))),
            }],
            init: None,
            shared: vec![media()],
            types: types.iter().map(|name| unit_enum(name)).collect(),
        }
    }

    #[test]
    fn plugins_declaring_the_same_type_names_share_an_app() {
        let camera = contract("Camera", &["SessionConfig", "PixelFormat", "Camera"]);
        let capture = contract(
            "ScreenCapture",
            &["SessionConfig", "PixelFormat", "Availability"],
        );
        let biometric = contract("Biometric", &["Availability"]);
        assert_eq!(
            check_swift_namespaces(&[&camera, &capture, &biometric]),
            Ok(())
        );
        let types = generate_swift_types(&camera);
        assert!(types.contains("public enum Camera {}\n"), "{types}");
        assert!(
            types.contains("extension Camera {\n    public enum SessionConfig"),
            "{types}"
        );
    }

    #[test]
    fn clashing_namespaces_fail_naming_both_plugins() {
        let clash = |a: &Contract, b: &Contract| {
            check_swift_namespaces(&[a, b]).expect_err("clash expected")
        };
        let camera = contract("Camera", &[]);
        let mut other = contract("Camera", &[]);
        other.plugin_id = "test.other".to_owned();
        let err = clash(&camera, &other);
        assert!(
            err.contains("`test.camera`") && err.contains("`test.other`"),
            "{err}"
        );
        // A namespace named like a symbol generated for another plugin.
        assert!(clash(&camera, &contract("CameraClient", &[])).contains("`CameraClient`"));
        assert!(clash(&camera, &contract("IstmoMedia", &[])).contains("shared types"));
        let err = check_swift_namespaces(&[&contract("Data", &[])]).expect_err("reserved");
        assert!(err.contains("runtime"), "{err}");
    }

    #[test]
    fn message_types_shadowing_names_inside_their_namespace_fail() {
        for name in ["Error", "Data", "IstmoMedia"] {
            let err = check_swift_namespaces(&[&contract("Camera", &[name])])
                .expect_err("shadowing expected");
            assert!(err.contains(&format!("`Camera.{name}`")), "{err}");
        }
    }
}
