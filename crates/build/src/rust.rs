//! Rust type generator.
//!
//! Emits `#[istmo::message] pub struct` / `pub enum` declarations for
//! every [`TypeDef`] the contract references, so a plugin author can
//! keep the [`Contract`] as the single source of truth for both the
//! Rust plugin surface and the Kotlin / Swift generated code.
//!
//! Typical wiring — a plugin crate ships a `build.rs`:
//!
//! ```ignore
//! use istmo_build::generate_rust_types;
//! fn main() {
//!     let contract = istmo_plugins::contract::permissions();
//!     let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap())
//!         .join("permissions_types.rs");
//!     std::fs::write(&out, generate_rust_types(&contract)).unwrap();
//! }
//! ```
//!
//! then `include!(concat!(env!("OUT_DIR"), "/permissions_types.rs"));`
//! from the plugin source.
//!
//! `NativeHandleId` is treated as an opaque wire alias — the generator
//! does not emit a declaration for it. The type lives in
//! `istmo_core::NativeHandleId` and is expected to be brought into scope
//! by the caller.

use std::fmt::Write as _;

use crate::contract::{Contract, EnumDef, StructDef, TypeDef, TypeRef};

/// Renders `#[message]`-annotated type declarations for `contract`.
#[must_use]
pub fn generate_rust_types(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    for ty in &contract.types {
        let _ = writeln!(out);
        match ty {
            TypeDef::Struct(s) => write_struct(&mut out, s),
            TypeDef::Enum(e) => write_enum(&mut out, e),
        }
    }
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
}

fn write_struct(out: &mut String, s: &StructDef) {
    let _ = writeln!(out, "#[::istmo_macros::message(bincode = \"::bincode\")]");
    let _ = writeln!(out, "#[derive(Debug, Clone, PartialEq)]");
    let _ = writeln!(out, "pub struct {} {{", s.name);
    for f in &s.fields {
        let _ = writeln!(out, "    pub {}: {},", to_rust_field(&f.name), rust_ty(&f.ty));
    }
    let _ = writeln!(out, "}}");
}

fn write_enum(out: &mut String, e: &EnumDef) {
    let _ = writeln!(out, "#[::istmo_macros::message(bincode = \"::bincode\")]");
    let _ = writeln!(out, "#[derive(Debug, Clone, PartialEq)]");
    let _ = writeln!(out, "pub enum {} {{", e.name);
    for v in &e.variants {
        if v.payload.is_empty() {
            let _ = writeln!(out, "    {},", v.name);
        } else {
            // Payload is currently one `TypeRef`; the tuple form drops
            // straight into Rust's `Variant(T)` syntax.
            let ty = rust_ty(&v.payload[0]);
            let _ = writeln!(out, "    {}({ty}),", v.name);
        }
    }
    let _ = writeln!(out, "}}");
}

fn rust_ty(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Unit => "()".to_owned(),
        TypeRef::Bool => "bool".to_owned(),
        TypeRef::U8 => "u8".to_owned(),
        TypeRef::I8 => "i8".to_owned(),
        TypeRef::U16 => "u16".to_owned(),
        TypeRef::I16 => "i16".to_owned(),
        TypeRef::U32 => "u32".to_owned(),
        TypeRef::I32 => "i32".to_owned(),
        TypeRef::U64 => "u64".to_owned(),
        TypeRef::I64 => "i64".to_owned(),
        TypeRef::F32 => "f32".to_owned(),
        TypeRef::F64 => "f64".to_owned(),
        TypeRef::String => "String".to_owned(),
        TypeRef::Bytes => "Vec<u8>".to_owned(),
        TypeRef::Vec(inner) => format!("Vec<{}>", rust_ty(inner)),
        TypeRef::Option(inner) => format!("Option<{}>", rust_ty(inner)),
        TypeRef::Named(name) => name.clone(),
    }
}

/// Convert a contract field name (`camelCase` in most bundled plugins,
/// e.g. `channelId`, `serverClientId`) to Rust `snake_case`. The
/// bincode wire is field-order-based, not name-based, so this is a pure
/// cosmetic choice for the emitted Rust surface. Matches the naming in
/// the hand-written `#[message]` types under `crates/plugins/src/`.
fn to_rust_field(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 2);
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i != 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}
