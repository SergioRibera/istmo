async fn enumerate_devices_impl() -> Result<Vec<CameraDevice>, CameraError> {
    let media = media_devices()?;
    let promise = media
        .enumerate_devices()
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    let value = JsFuture::from(promise)
        .await
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    let array: Array = value
        .dyn_into()
        .map_err(|_| CameraError::Backend("enumerateDevices returned non-array".into()))?;

    let mut out = Vec::new();
    for raw in array.iter() {
        let info: MediaDeviceInfo = match raw.dyn_into() {
            Ok(info) => info,
            Err(_) => continue,
        };
        if info.kind() != MediaDeviceKind::Videoinput {
            continue;
        }
        let label = info.label();
        out.push(CameraDevice {
            id: info.device_id(),
            label: if label.is_empty() {
                "Camera".into()
            } else {
                label.clone()
            },
            facing: guess_facing(&label),
            lens: LensKind::Wide,
            physical_sensors: Vec::new(),
            capabilities: CameraCapabilities {
                min_zoom: 1.0,
                max_zoom: 1.0,
                optical_zoom_steps: Vec::new(),
                focal_lengths_mm: Vec::new(),
                supports_flash: false,
                supports_torch: false,
                supports_autofocus: true,
                supports_manual_focus: false,
                supports_ois: false,
                supports_eis: false,
                supports_hdr: false,
                supports_depth: false,
                supports_raw: false,
                max_still_resolution: Resolution {
                    width: 0,
                    height: 0,
                },
            },
            supported_formats: Vec::new(),
        });
    }
    Ok(out)
}

async fn access_status_impl() -> Result<AccessStatus, CameraError> {
    let window = window_handle()?;
    let navigator = window.navigator();
    let permissions = navigator.permissions().map_err(|err| {
        CameraError::Backend(format!("permissions API unavailable: {}", js_err(err)))
    })?;
    let descriptor = Object::new();
    Reflect::set(&descriptor, &"name".into(), &"camera".into())
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    let promise = permissions.query(&descriptor).map_err(|err| {
        CameraError::Backend(format!("permissions.query('camera') rejected: {}", js_err(err)))
    })?;
    let status: PermissionStatus = JsFuture::from(promise)
        .await
        .map_err(|err| CameraError::Backend(js_err(err)))?
        .dyn_into()
        .map_err(|_| CameraError::Backend("permissions.query returned non-PermissionStatus".into()))?;
    Ok(match status.state() {
        PermissionState::Granted => AccessStatus::Granted,
        PermissionState::Denied => AccessStatus::Denied,
        PermissionState::Prompt => AccessStatus::NotDetermined,
        _ => AccessStatus::NotDetermined,
    })
}

async fn request_access_impl() -> Result<AccessStatus, CameraError> {
    let media = media_devices()?;
    let constraints = MediaStreamConstraints::new();
    constraints.set_video(&JsValue::TRUE);
    let promise = media
        .get_user_media_with_constraints(&constraints)
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    match JsFuture::from(promise).await {
        Ok(value) => {
            if let Ok(stream) = value.dyn_into::<MediaStream>() {
                stop_tracks(&stream);
            }
            Ok(AccessStatus::Granted)
        }
        Err(err) => {
            let msg = js_err(err);
            if msg.contains("NotAllowed") || msg.contains("Permission") {
                Ok(AccessStatus::Denied)
            } else {
                Err(CameraError::Backend(msg))
            }
        }
    }
}

/// Result of `open_impl` — carries both the wire response and the
/// session entry that needs to be inserted into `WebCamera.sessions`
/// synchronously after the relay resolves. `SendWrapper<WebSessionEntry>`
/// is `Send` on wasm32 (single-threaded); the outer struct becomes
/// `Send` for the oneshot relay without any `unsafe impl`.
struct OpenResult {
    session: CameraSession,
    entry: SendWrapper<WebSessionEntry>,
}

async fn open_impl(
    id: NativeHandleId,
    pool_depth: usize,
    config: SessionConfig,
) -> Result<OpenResult, CameraError> {
    let _ = id;
    let window = window_handle()?;
    let document = window
        .document()
        .ok_or_else(|| CameraError::Backend("no `document` on window".into()))?;
    let media = media_devices()?;

    let constraints = build_constraints(&config);
    let promise = media
        .get_user_media_with_constraints(&constraints)
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    let stream: MediaStream = JsFuture::from(promise)
        .await
        .map_err(classify_get_user_media_error)?
        .dyn_into()
        .map_err(|_| CameraError::Backend("getUserMedia returned non-stream".into()))?;

    let (video, canvas, ctx) = install_dom(&document, &stream)?;
    wait_for_metadata(&video).await?;

    let width = video.video_width().max(1);
    let height = video.video_height().max(1);
    canvas.set_width(width);
    canvas.set_height(height);

    let fps = config.target_fps.unwrap_or(30).max(1);
    let interval_ms = ((1000.0 / f64::from(fps)).round() as i32).max(1);

    let (tx, rx) = flume::bounded::<CameraFrame>(pool_depth);
    let dropped = Rc::new(AtomicU64::new(0));
    let seq = Rc::new(AtomicU64::new(0));
    let pixel_format = config.pixel_format;

    let pump = make_pump(
        video.clone(),
        ctx.clone(),
        width,
        height,
        pixel_format,
        tx,
        Rc::clone(&dropped),
        Rc::clone(&seq),
    );

    let interval_handle = window
        .set_interval_with_callback_and_timeout_and_arguments_0(
            pump.as_ref().unchecked_ref(),
            interval_ms,
        )
        .map_err(|err| CameraError::Backend(js_err(err)))?;

    let negotiated = NegotiatedFormat {
        resolution: Resolution { width, height },
        pixel_format,
        fps,
        rotation_degrees: 0,
    };

    Ok(OpenResult {
        session: CameraSession {
            session: id,
            negotiated,
        },
        entry: SendWrapper::new(WebSessionEntry {
            stream,
            video,
            canvas,
            ctx,
            interval_handle,
            pump,
            rx,
            pixel_format,
            width,
            height,
        }),
    })
}

async fn apply_controls_impl(
    track: SendWrapper<MediaStreamTrack>,
    controls: CameraControls,
) -> Result<AppliedControls, CameraError> {
    if controls.zoom.is_some()
        || controls.torch.is_some()
        || controls.exposure_compensation_ev.is_some()
        || controls.white_balance.is_some()
    {
        let advanced = Array::new();
        let entry_obj = Object::new();
        if let Some(zoom) = controls.zoom {
            let _ = Reflect::set(&entry_obj, &"zoom".into(), &JsValue::from_f64(zoom.into()));
        }
        if let Some(torch) = controls.torch {
            let _ = Reflect::set(&entry_obj, &"torch".into(), &JsValue::from_bool(torch));
        }
        if let Some(ev) = controls.exposure_compensation_ev {
            let _ = Reflect::set(
                &entry_obj,
                &"exposureCompensation".into(),
                &JsValue::from_f64(ev.into()),
            );
        }
        if let Some(wb) = controls.white_balance {
            let mode = match wb {
                WhiteBalanceMode::Auto => "continuous",
                _ => "manual",
            };
            let _ = Reflect::set(
                &entry_obj,
                &"whiteBalanceMode".into(),
                &JsValue::from_str(mode),
            );
        }
        advanced.push(&entry_obj);

        let constraints = Object::new();
        let _ = Reflect::set(&constraints, &"advanced".into(), &advanced);
        if let Ok(p) = track.apply_constraints_with_constraints(constraints.unchecked_ref()) {
            let _ = JsFuture::from(p).await;
        }
    }

    Ok(AppliedControls {
        zoom: controls.zoom.unwrap_or(1.0),
        torch: controls.torch.unwrap_or(false),
        focus: controls.focus.unwrap_or(FocusMode::ContinuousVideo),
        exposure_compensation_ev: controls.exposure_compensation_ev.unwrap_or(0.0),
        white_balance: controls.white_balance.unwrap_or(WhiteBalanceMode::Auto),
        flash: controls.flash.unwrap_or(FlashMode::Off),
    })
}

// -------------------------------------------------------------------
// DOM / `MediaStream` helpers
