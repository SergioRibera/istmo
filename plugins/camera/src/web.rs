// -------------------------------------------------------------------
// `Send` relay. Each inner future runs on the single-threaded wasm
// executor via `spawn_local`; the outer `async fn` only waits on the
// resulting `flume::Receiver`, which is `Send`.
// -------------------------------------------------------------------

/// Relay a `!Send` wasm-local future through a `Send` channel so the
/// plugin trait's `async fn` return type stays `Send`.
///
/// The closure must own everything the inner future needs — we move
/// it into `spawn_local`, which drives it on the wasm single-threaded
/// executor. The returned future only awaits the `oneshot::Receiver`,
/// which is `Send` when `T: Send`.
fn relay<F, FF, T>(make_fut: F) -> impl std::future::Future<Output = Result<T, CameraError>> + Send
where
    F: FnOnce() -> FF + Send + 'static,
    FF: std::future::Future<Output = Result<T, CameraError>> + 'static,
    T: Send + 'static,
{
    let (tx, rx) = oneshot::channel::<Result<T, CameraError>>();
    wasm_bindgen_futures::spawn_local(async move {
        let _ = tx.send(make_fut().await);
    });
    async move {
        rx.await
            .unwrap_or_else(|_| Err(CameraError::Backend("spawn task dropped".into())))
    }
}

