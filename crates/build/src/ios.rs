//! iOS background execution + entitlements codegen.
//!
//! iOS has no equivalent of Android's `Service`. Long-running work must map
//! to a small set of system-supplied primitives; this module models the
//! honest subset:
//!
//! * [`BackgroundKind::Refresh`] — [`BGAppRefreshTask`]: short opportunistic
//!   wakeups. The system picks the actual firing time; `interval_minutes` is
//!   a *minimum* between runs.
//! * [`BackgroundKind::Processing`] — [`BGProcessingTask`]: heavier jobs the
//!   system may schedule when the device is idle / on power.
//! * [`BackgroundKind::Continuous`] — the legitimate always-on background
//!   modes ([`ContinuousMode`]). Each requires the matching entry in
//!   `UIBackgroundModes` in `Info.plist`.
//!
//! [`BGAppRefreshTask`]: https://developer.apple.com/documentation/backgroundtasks/bgapprefreshtask
//! [`BGProcessingTask`]: https://developer.apple.com/documentation/backgroundtasks/bgprocessingtask

use std::fmt::Write as _;

use crate::entitlements::IosEntitlements;

/// How a Rust-side background task should be surfaced to iOS.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum BackgroundKind {
    /// Short opportunistic refresh via `BGAppRefreshTaskRequest`.
    Refresh { interval_minutes: u32 },
    /// Heavier work via `BGProcessingTaskRequest`.
    Processing {
        requires_power: bool,
        requires_network: bool,
    },
    /// Legitimate always-on background mode.
    Continuous(ContinuousMode),
}

/// The always-on background modes iOS lets an app declare in Info.plist's
/// `UIBackgroundModes`. Anything outside this list is unsupported.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ContinuousMode {
    Audio,
    Location,
    Voip,
    ExternalAccessory,
    BluetoothCentral,
    BluetoothPeripheral,
}

impl ContinuousMode {
    /// The exact string iOS expects in the `UIBackgroundModes` array.
    #[must_use]
    pub const fn info_plist_value(self) -> &'static str {
        match self {
            Self::Audio => "audio",
            Self::Location => "location",
            Self::Voip => "voip",
            Self::ExternalAccessory => "external-accessory",
            Self::BluetoothCentral => "bluetooth-central",
            Self::BluetoothPeripheral => "bluetooth-peripheral",
        }
    }
}

/// Configuration of a single iOS background task.
///
/// The `task_identifier` is what `BGTaskScheduler.register(forTaskWithIdentifier:)`
/// expects and must be listed under `BGTaskSchedulerPermittedIdentifiers` in
/// Info.plist — the generator emits that fragment automatically for
/// `Refresh` and `Processing` variants.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IosBackgroundContract {
    /// Wire plugin id matching the Rust adapter's `PLUGIN_ID`.
    pub plugin_id: String,
    /// Swift class name for the generated shim.
    pub class_name: String,
    /// Reverse-DNS task identifier registered with `BGTaskScheduler`. For
    /// [`BackgroundKind::Continuous`] variants this is ignored (no
    /// `BGTaskScheduler` registration needed).
    pub task_identifier: Option<String>,
    /// Which system primitive to bind to.
    pub kind: BackgroundKind,
}

/// Bundle returned by [`generate_ios_background`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IosBackgroundArtifacts {
    /// Contents of `<ClassName>.swift`.
    pub swift: String,
    /// XML fragment ready to merge into Info.plist. Keys are wrapped so a
    /// downstream tool can concatenate multiple fragments inside one
    /// `<dict>` and run `plutil -convert` afterwards.
    pub info_plist_fragment: String,
}

/// Render Swift + Info.plist artefacts for `contract`.
#[must_use]
pub fn generate_ios_background(contract: &IosBackgroundContract) -> IosBackgroundArtifacts {
    IosBackgroundArtifacts {
        swift: render_swift(contract),
        info_plist_fragment: render_info_plist(contract),
    }
}

fn render_swift(contract: &IosBackgroundContract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// background plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
    let _ = writeln!(out, "import BackgroundTasks");
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out);
    match &contract.kind {
        BackgroundKind::Refresh { .. } | BackgroundKind::Processing { .. } => {
            render_bg_task_shim(&mut out, contract);
        }
        BackgroundKind::Continuous(mode) => {
            render_continuous_shim(&mut out, contract, *mode);
        }
    }
    out
}

fn render_bg_task_shim(out: &mut String, contract: &IosBackgroundContract) {
    let task_id = contract
        .task_identifier
        .as_deref()
        .unwrap_or("<TASK_IDENTIFIER_REQUIRED>");
    let (task_type, submit_body) = match &contract.kind {
        BackgroundKind::Refresh { interval_minutes } => {
            let body = format!(
                "        let request = BGAppRefreshTaskRequest(identifier: TASK_ID)\n        \
                 request.earliestBeginDate = Date(timeIntervalSinceNow: TimeInterval({interval_minutes} * 60))\n        \
                 try? BGTaskScheduler.shared.submit(request)"
            );
            ("BGAppRefreshTask", body)
        }
        BackgroundKind::Processing {
            requires_power,
            requires_network,
        } => {
            let body = format!(
                "        let request = BGProcessingTaskRequest(identifier: TASK_ID)\n        \
                 request.requiresExternalPower = {requires_power}\n        \
                 request.requiresNetworkConnectivity = {requires_network}\n        \
                 try? BGTaskScheduler.shared.submit(request)"
            );
            ("BGProcessingTask", body)
        }
        BackgroundKind::Continuous(_) => unreachable!("handled above"),
    };

    let _ = writeln!(
        out,
        "/// Generated `BGTaskScheduler` shim for istmo background plugin"
    );
    let _ = writeln!(out, "/// `{}`.", contract.plugin_id);
    let _ = writeln!(out, "public enum {} {{", contract.class_name);
    let _ = writeln!(
        out,
        "    public static let PLUGIN_ID: String = \"{}\"",
        contract.plugin_id
    );
    let _ = writeln!(out, "    public static let TASK_ID: String = \"{task_id}\"");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    /// Registers the {task_type} handler with the system scheduler."
    );
    let _ = writeln!(
        out,
        "    /// Call once from `application(_:didFinishLaunchingWithOptions:)`."
    );
    let _ = writeln!(out, "    public static func register() {{");
    let _ = writeln!(
        out,
        "        BGTaskScheduler.shared.register(forTaskWithIdentifier: TASK_ID, using: nil) {{ task in"
    );
    let _ = writeln!(out, "            handle(task: task as! {task_type})");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    /// Submits a fresh scheduler request. Call after a successful"
    );
    let _ = writeln!(
        out,
        "    /// completion so the OS considers the app for its next slot."
    );
    let _ = writeln!(out, "    public static func schedule() {{");
    let _ = writeln!(out, "{submit_body}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(out, "    private static func handle(task: {task_type}) {{");
    let _ = writeln!(
        out,
        "        // Forward to the Rust adapter registered under PLUGIN_ID."
    );
    let _ = writeln!(
        out,
        "        // The adapter's `on_start` runs on a dedicated task; the"
    );
    let _ = writeln!(
        out,
        "        // `expirationHandler` cancels it cooperatively so the OS"
    );
    let _ = writeln!(out, "        // does not force-kill the process.");
    let _ = writeln!(out, "        task.expirationHandler = {{");
    let _ = writeln!(
        out,
        "            IstmoRuntime.shared.cancel(pluginId: PLUGIN_ID)"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "        Task {{");
    let _ = writeln!(
        out,
        "            let ok = await IstmoRuntime.shared.callVoid(pluginId: PLUGIN_ID, method: \"on_start\", payload: Data())"
    );
    let _ = writeln!(out, "            task.setTaskCompleted(success: ok)");
    let _ = writeln!(out, "            schedule()");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
}

fn render_continuous_shim(
    out: &mut String,
    contract: &IosBackgroundContract,
    mode: ContinuousMode,
) {
    let _ = writeln!(
        out,
        "/// Generated always-on background shim for istmo background plugin"
    );
    let _ = writeln!(
        out,
        "/// `{}` (mode: {}).",
        contract.plugin_id,
        mode.info_plist_value()
    );
    let _ = writeln!(out, "///");
    let _ = writeln!(
        out,
        "/// The plugin's Rust adapter is expected to be running for the entire"
    );
    let _ = writeln!(
        out,
        "/// app lifetime; there is no scheduler to register with."
    );
    let _ = writeln!(out, "public enum {} {{", contract.class_name);
    let _ = writeln!(
        out,
        "    public static let PLUGIN_ID: String = \"{}\"",
        contract.plugin_id
    );
    let _ = writeln!(
        out,
        "    public static let BACKGROUND_MODE: String = \"{}\"",
        mode.info_plist_value()
    );
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    /// Call from `application(_:didFinishLaunchingWithOptions:)`."
    );
    let _ = writeln!(out, "    public static func start() {{");
    let _ = writeln!(out, "        Task {{");
    let _ = writeln!(
        out,
        "            _ = await IstmoRuntime.shared.callVoid(pluginId: PLUGIN_ID, method: \"on_start\", payload: Data())"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
}

fn render_info_plist(contract: &IosBackgroundContract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "<!-- GENERATED by istmo-build - DO NOT EDIT. -->");
    let _ = writeln!(out, "<!-- background plugin id: {} -->", contract.plugin_id);
    match &contract.kind {
        BackgroundKind::Refresh { .. } | BackgroundKind::Processing { .. } => {
            let task_id = contract
                .task_identifier
                .as_deref()
                .unwrap_or("<TASK_IDENTIFIER_REQUIRED>");
            let _ = writeln!(out, "<key>BGTaskSchedulerPermittedIdentifiers</key>");
            let _ = writeln!(out, "<array>");
            let _ = writeln!(out, "    <string>{task_id}</string>");
            let _ = writeln!(out, "</array>");
        }
        BackgroundKind::Continuous(mode) => {
            let _ = writeln!(out, "<key>UIBackgroundModes</key>");
            let _ = writeln!(out, "<array>");
            let _ = writeln!(out, "    <string>{}</string>", mode.info_plist_value());
            let _ = writeln!(out, "</array>");
        }
    }
    out
}

/// Returns the entitlements this background contract needs enabled, if any.
///
/// This is a convenience for `build.rs` scripts that want to aggregate all
/// entitlement requirements from a workspace's registered plugins into a
/// single `.entitlements` file. See [`IosEntitlements::render`].
#[must_use]
pub fn required_entitlements(contract: &IosBackgroundContract) -> IosEntitlements {
    let mut ent = IosEntitlements::new();
    if matches!(
        &contract.kind,
        BackgroundKind::Continuous(ContinuousMode::Voip)
    ) {
        // VoIP calls specifically require the PushKit entitlement in
        // addition to the UIBackgroundModes entry.
        ent.add_string("com.apple.developer.pushkit.unrestricted-voip", "true");
    }
    ent
}
