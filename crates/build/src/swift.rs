//! Swift `protocol` generator. Mirrors the Kotlin generator in shape.

use std::fmt::Write as _;

use crate::contract::{Contract, Method, MethodKind};

/// Renders the Swift surface for `contract`.
#[must_use]
pub fn generate_swift(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    write_protocol(&mut out, contract);
    if let Some(init) = &contract.init {
        write_factory(&mut out, contract, init);
    }
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
}

fn write_protocol(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "protocol {} {{", contract.type_name);
    for (i, method) in contract.methods.iter().enumerate() {
        if i > 0 {
            let _ = writeln!(out);
        }
        write_method(out, method);
    }
    let _ = writeln!(out, "}}");
}

fn write_method(out: &mut String, method: &Method) {
    let args = format_args(method);
    match method.kind {
        MethodKind::Unary => {
            let _ = writeln!(
                out,
                "    func {}({}) async throws -> {}",
                method.name,
                args,
                method.returns.to_swift(),
            );
        }
        MethodKind::Stream => {
            let _ = writeln!(
                out,
                "    func {}({}) -> AsyncThrowingStream<{}, Error>",
                method.name,
                args,
                method.returns.to_swift(),
            );
        }
    }
}

fn format_args(method: &Method) -> String {
    method
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.ty.to_swift()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn write_factory(out: &mut String, contract: &Contract, init: &crate::contract::TypeRef) {
    let _ = writeln!(out);
    let _ = writeln!(out, "// Factory contract for `acquire_with`.");
    let _ = writeln!(out, "protocol {}Factory {{", contract.type_name);
    let _ = writeln!(
        out,
        "    func create(config: {}) async throws -> {}",
        init.to_swift(),
        contract.type_name,
    );
    let _ = writeln!(out, "}}");
}
