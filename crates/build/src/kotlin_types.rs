//! Kotlin type + codec generator.
//!
//! Emits `data class` / `enum class` / `sealed class` declarations for
//! every [`TypeDef`] the contract references, plus a [`<T>CodecsImpl`]
//! implementing the codec interface the host dispatcher generator emits.
//!
//! Wire encoding rules mirror `crates/plugins/src/*.rs`'s `#[message]`
//! output:
//!
//! * Struct — fields in declaration order, no length prefix.
//! * Enum without payload — u32 varint discriminant.
//! * Enum with payload — u32 varint discriminant + per-variant payload.
//! * Vec — u64 varint length + elements.
//! * Option — 0x00 (None) or 0x01 + value.
//!
//! `NativeHandleId` is treated as an opaque `Long` typealias — the
//! generator emits `readNativeHandleId` / `writeNativeHandleId` mapping
//! to a plain `Long` varint but does not emit a `typealias`; the demo's
//! runtime declares that in `PluginHandler.kt`.

use std::fmt::Write as _;

use crate::contract::{Contract, EnumDef, StructDef, TypeDef, TypeRef};

/// Renders type declarations for `contract`.
#[must_use]
pub fn generate_kotlin_types(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    for ty in &contract.types {
        writeln!(out).ok();
        match ty {
            TypeDef::Struct(s) => write_struct(&mut out, s),
            TypeDef::Enum(e) => write_enum(&mut out, e),
        }
    }
    out
}

/// Renders the codec impl class for `contract`.
#[must_use]
pub fn generate_kotlin_codecs(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    let _ = writeln!(out, "import java.io.ByteArrayOutputStream");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "class {}CodecsImpl : {}Codecs {{",
        contract.type_name, contract.type_name,
    );
    for ty in &contract.types {
        let _ = writeln!(out);
        match ty {
            TypeDef::Struct(s) => write_struct_codec(&mut out, s),
            TypeDef::Enum(e) => write_enum_codec(&mut out, e),
        }
    }
    if contract_references_native_handle(contract) {
        let _ = writeln!(out);
        write_native_handle_codec(&mut out);
    }
    let _ = writeln!(out, "}}");
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
}

// ---- Type declarations --------------------------------------------------

fn write_struct(out: &mut String, s: &StructDef) {
    let _ = writeln!(out, "data class {}(", s.name);
    for (i, f) in s.fields.iter().enumerate() {
        let comma = if i + 1 == s.fields.len() { "" } else { "," };
        let _ = writeln!(out, "    val {}: {}{}", f.name, f.ty.to_kotlin(), comma);
    }
    let _ = writeln!(out, ")");
}

fn write_enum(out: &mut String, e: &EnumDef) {
    if e.variants.iter().all(|v| v.payload.is_empty()) {
        let _ = writeln!(out, "enum class {} {{", e.name);
        for (i, v) in e.variants.iter().enumerate() {
            let comma = if i + 1 == e.variants.len() { "" } else { "," };
            let _ = writeln!(out, "    {}{}", v.name, comma);
        }
    } else {
        let _ = writeln!(out, "sealed class {} {{", e.name);
        for v in &e.variants {
            if v.payload.is_empty() {
                let _ = writeln!(out, "    object {} : {}()", v.name, e.name);
            } else {
                // Payload is currently modelled as a single `TypeRef` per
                // variant; when a variant grows fields, extend `EnumVariant`
                // with a struct-like shape.
                let ty = v.payload[0].to_kotlin();
                let _ = writeln!(
                    out,
                    "    data class {}(val value: {}) : {}()",
                    v.name, ty, e.name,
                );
            }
        }
    }
    let _ = writeln!(out, "}}");
}

// ---- Codec impls --------------------------------------------------------

fn write_struct_codec(out: &mut String, s: &StructDef) {
    // read
    let _ = writeln!(
        out,
        "    override fun read{}(bytes: ByteArray, offset: Int): Bincode.Decoded<{}> {{",
        s.name, s.name,
    );
    let _ = writeln!(out, "        var cursor = offset");
    for f in &s.fields {
        write_read_field(out, "        ", &f.name, &f.ty);
    }
    let field_list = s
        .fields
        .iter()
        .map(|f| format!("{} = {}", f.name, f.name))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        out,
        "        return Bincode.Decoded({}({}), cursor)",
        s.name, field_list
    );
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    // write
    let _ = writeln!(
        out,
        "    override fun write{}(out: ByteArrayOutputStream, value: {}) {{",
        s.name, s.name,
    );
    for f in &s.fields {
        write_write_field(out, "        ", &format!("value.{}", f.name), &f.ty);
    }
    let _ = writeln!(out, "    }}");
}

fn write_enum_codec(out: &mut String, e: &EnumDef) {
    let has_payload = e.variants.iter().any(|v| !v.payload.is_empty());
    // ---- read
    let _ = writeln!(
        out,
        "    override fun read{}(bytes: ByteArray, offset: Int): Bincode.Decoded<{}> {{",
        e.name, e.name,
    );
    if has_payload {
        let _ = writeln!(out, "        var cursor = offset");
        let _ = writeln!(
            out,
            "        val disc = Bincode.readVarintU64(bytes, cursor)"
        );
        let _ = writeln!(out, "        cursor = disc.consumed");
        let _ = writeln!(out, "        return when (disc.value.toInt()) {{");
        for (i, v) in e.variants.iter().enumerate() {
            if v.payload.is_empty() {
                let _ = writeln!(
                    out,
                    "            {i} -> Bincode.Decoded({}.{}, cursor)",
                    e.name, v.name,
                );
            } else {
                let _ = writeln!(out, "            {i} -> {{");
                write_read_bindings_for(out, "                ", "inner", &v.payload[0]);
                let _ = writeln!(
                    out,
                    "                Bincode.Decoded({}.{}(inner) as {}, cursor)",
                    e.name, v.name, e.name,
                );
                let _ = writeln!(out, "            }}");
            }
        }
        let _ = writeln!(
            out,
            "            else -> error(\"{}: unknown discriminant ${{disc.value}}\")",
            e.name,
        );
        let _ = writeln!(out, "        }}");
    } else {
        let _ = writeln!(out, "        val d = Bincode.readVarintU64(bytes, offset)");
        let _ = writeln!(
            out,
            "        val variant = {}.entries.getOrNull(d.value.toInt())",
            e.name,
        );
        let _ = writeln!(
            out,
            "            ?: error(\"{}: unknown discriminant ${{d.value}}\")",
            e.name,
        );
        let _ = writeln!(out, "        return Bincode.Decoded(variant, d.consumed)");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    // ---- write
    let _ = writeln!(
        out,
        "    override fun write{}(out: ByteArrayOutputStream, value: {}) {{",
        e.name, e.name,
    );
    if has_payload {
        let _ = writeln!(out, "        when (value) {{");
        for (i, v) in e.variants.iter().enumerate() {
            if v.payload.is_empty() {
                let _ = writeln!(
                    out,
                    "            {}.{} -> Bincode.writeEnumDiscriminant(out, {i})",
                    e.name, v.name,
                );
            } else {
                let _ = writeln!(out, "            is {}.{} -> {{", e.name, v.name);
                let _ = writeln!(
                    out,
                    "                Bincode.writeEnumDiscriminant(out, {i})"
                );
                write_write_field(out, "                ", "value.value", &v.payload[0]);
                let _ = writeln!(out, "            }}");
            }
        }
        let _ = writeln!(out, "        }}");
    } else {
        let _ = writeln!(
            out,
            "        Bincode.writeEnumDiscriminant(out, value.ordinal)",
        );
    }
    let _ = writeln!(out, "    }}");
}

fn write_native_handle_codec(out: &mut String) {
    let _ = writeln!(
        out,
        "    override fun readNativeHandleId(bytes: ByteArray, offset: Int): Bincode.Decoded<NativeHandleId> {{",
    );
    let _ = writeln!(out, "        return Bincode.readVarintU64(bytes, offset)");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    override fun writeNativeHandleId(out: ByteArrayOutputStream, value: NativeHandleId) {{",
    );
    let _ = writeln!(out, "        Bincode.writeVarintU64(out, value)");
    let _ = writeln!(out, "    }}");
}

// ---- Field read/write helpers -------------------------------------------

/// Reads the value for `field_name` (advancing `cursor`) into a local
/// `val <field_name>: T`.
fn write_read_field(out: &mut String, indent: &str, field_name: &str, ty: &TypeRef) {
    write_read_bindings_for(out, indent, field_name, ty);
}

fn write_read_bindings_for(out: &mut String, indent: &str, binding: &str, ty: &TypeRef) {
    if let TypeRef::Named(name) = ty {
        let _ = writeln!(out, "{indent}val d_{binding} = read{name}(bytes, cursor)");
    } else {
        let expr = read_expr(ty);
        let _ = writeln!(out, "{indent}val d_{binding} = {expr}");
    }
    let _ = writeln!(out, "{indent}cursor = d_{binding}.consumed");
    let _ = writeln!(out, "{indent}val {binding} = d_{binding}.value");
}

fn read_expr(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Bool => "Bincode.readBool(bytes, cursor)".to_owned(),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let cast = kt_int_cast(ty);
            format!(
                "Bincode.readVarintU64(bytes, cursor).let {{ Bincode.Decoded(it.value{cast}, it.consumed) }}"
            )
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let cast = kt_int_cast(ty);
            format!(
                "Bincode.readVarintI64(bytes, cursor).let {{ Bincode.Decoded(it.value{cast}, it.consumed) }}"
            )
        }
        TypeRef::F32 => "Bincode.readF32(bytes, cursor)".to_owned(),
        TypeRef::F64 => "Bincode.readF64(bytes, cursor)".to_owned(),
        TypeRef::String => "Bincode.readString(bytes, cursor)".to_owned(),
        TypeRef::Bytes => "Bincode.readBytes(bytes, cursor)".to_owned(),
        TypeRef::Vec(inner) => {
            let inner_lambda = read_lambda(inner);
            format!("Bincode.readVec(bytes, cursor) {{ p, o -> {inner_lambda} }}")
        }
        TypeRef::Option(inner) => {
            let inner_lambda = read_lambda(inner);
            format!("Bincode.readOption(bytes, cursor) {{ p, o -> {inner_lambda} }}")
        }
        TypeRef::Unit => "Bincode.Decoded(Unit, cursor)".to_owned(),
        TypeRef::Named(name) => format!("read{name}(bytes, cursor)"),
    }
}

fn read_lambda(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Named(name) => format!("read{name}(p, o)"),
        TypeRef::String => "Bincode.readString(p, o)".to_owned(),
        TypeRef::Bool => "Bincode.readBool(p, o)".to_owned(),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let cast = kt_int_cast(ty);
            format!(
                "Bincode.readVarintU64(p, o).let {{ Bincode.Decoded(it.value{cast}, it.consumed) }}",
            )
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let cast = kt_int_cast(ty);
            format!(
                "Bincode.readVarintI64(p, o).let {{ Bincode.Decoded(it.value{cast}, it.consumed) }}",
            )
        }
        TypeRef::F32 => "Bincode.readF32(p, o)".to_owned(),
        TypeRef::F64 => "Bincode.readF64(p, o)".to_owned(),
        TypeRef::Bytes => "Bincode.readBytes(p, o)".to_owned(),
        TypeRef::Vec(inner) => {
            let inner_lambda = read_lambda(inner);
            format!("Bincode.readVec(p, o) {{ pp, oo -> {inner_lambda} }}")
        }
        TypeRef::Option(inner) => {
            let inner_lambda = read_lambda(inner);
            format!("Bincode.readOption(p, o) {{ pp, oo -> {inner_lambda} }}")
        }
        TypeRef::Unit => "Bincode.Decoded(Unit, o)".to_owned(),
    }
}

fn write_write_field(out: &mut String, indent: &str, binding: &str, ty: &TypeRef) {
    match ty {
        TypeRef::Named(name) => {
            let _ = writeln!(out, "{indent}write{name}(out, {binding})");
        }
        TypeRef::String => {
            let _ = writeln!(out, "{indent}Bincode.writeString(out, {binding})");
        }
        TypeRef::Bool => {
            let _ = writeln!(out, "{indent}Bincode.writeBool(out, {binding})");
        }
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVarintU64(out, {binding}.toLong())",
            );
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVarintI64(out, {binding}.toLong())",
            );
        }
        TypeRef::F32 => {
            let _ = writeln!(out, "{indent}Bincode.writeF32(out, {binding})");
        }
        TypeRef::F64 => {
            let _ = writeln!(out, "{indent}Bincode.writeF64(out, {binding})");
        }
        TypeRef::Bytes => {
            let _ = writeln!(out, "{indent}Bincode.writeBytes(out, {binding})");
        }
        TypeRef::Unit => {
            let _ = writeln!(out, "{indent}// () — nothing to encode");
        }
        TypeRef::Vec(inner) => {
            let inner_lambda = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVec(out, {binding}) {{ s, v -> {inner_lambda} }}",
            );
        }
        TypeRef::Option(inner) => {
            let inner_lambda = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeOption(out, {binding}) {{ s, v -> {inner_lambda} }}",
            );
        }
    }
}

fn write_lambda(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Named(name) => format!("write{name}(s, v)"),
        TypeRef::String => "Bincode.writeString(s, v)".to_owned(),
        TypeRef::Bool => "Bincode.writeBool(s, v)".to_owned(),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            "Bincode.writeVarintU64(s, v.toLong())".to_owned()
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            "Bincode.writeVarintI64(s, v.toLong())".to_owned()
        }
        TypeRef::F32 => "Bincode.writeF32(s, v)".to_owned(),
        TypeRef::F64 => "Bincode.writeF64(s, v)".to_owned(),
        TypeRef::Bytes => "Bincode.writeBytes(s, v)".to_owned(),
        TypeRef::Unit => "/* () */".to_owned(),
        TypeRef::Vec(inner) => {
            let inner_lambda = write_lambda(inner);
            format!("Bincode.writeVec(s, v) {{ ss, vv -> {inner_lambda} }}")
        }
        TypeRef::Option(inner) => {
            let inner_lambda = write_lambda(inner);
            format!("Bincode.writeOption(s, v) {{ ss, vv -> {inner_lambda} }}")
        }
    }
}

const fn kt_int_cast(ty: &TypeRef) -> &'static str {
    match ty {
        TypeRef::U8 => ".toUByte()",
        TypeRef::U16 => ".toUShort()",
        TypeRef::U32 => ".toUInt()",
        TypeRef::U64 => ".toULong()",
        TypeRef::I8 => ".toByte()",
        TypeRef::I16 => ".toShort()",
        TypeRef::I32 => ".toInt()",
        _ => "",
    }
}

fn contract_references_native_handle(contract: &Contract) -> bool {
    fn walks(ty: &TypeRef) -> bool {
        match ty {
            TypeRef::Named(n) => n == "NativeHandleId",
            TypeRef::Vec(inner) | TypeRef::Option(inner) => walks(inner),
            _ => false,
        }
    }
    contract.methods.iter().any(|m| {
        m.args.iter().any(|a| walks(&a.ty))
            || walks(&m.returns)
            || m.error.as_ref().is_some_and(walks)
    }) || contract.init.as_ref().is_some_and(walks)
}
