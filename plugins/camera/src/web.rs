fn window_handle() -> Result<Window, CameraError> {
    web_sys::window().ok_or_else(|| CameraError::Backend("no `window` global".into()))
}

fn media_devices() -> Result<web_sys::MediaDevices, CameraError> {
    let window = window_handle()?;
    window
        .navigator()
        .media_devices()
        .map_err(|err| CameraError::Backend(format!("navigator.mediaDevices: {}", js_err(err))))
}

fn install_dom(
    document: &Document,
    stream: &MediaStream,
) -> Result<(HtmlVideoElement, HtmlCanvasElement, CanvasRenderingContext2d), CameraError> {
    let video: HtmlVideoElement = document
        .create_element("video")
        .map_err(|err| CameraError::Backend(js_err(err)))?
        .dyn_into()
        .map_err(|_| CameraError::Backend("createElement('video') cast failed".into()))?;
    video.set_autoplay(true);
    video.set_muted(true);
    video
        .set_attribute("playsinline", "true")
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    hide_offscreen(video.as_ref());
    video.set_src_object(Some(stream));

    let canvas: HtmlCanvasElement = document
        .create_element("canvas")
        .map_err(|err| CameraError::Backend(js_err(err)))?
        .dyn_into()
        .map_err(|_| CameraError::Backend("createElement('canvas') cast failed".into()))?;
    hide_offscreen(canvas.as_ref());

    let body = document
        .body()
        .ok_or_else(|| CameraError::Backend("document has no body".into()))?;
    body.append_child(&video)
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    body.append_child(&canvas)
        .map_err(|err| CameraError::Backend(js_err(err)))?;

    let ctx: CanvasRenderingContext2d = canvas
        .get_context("2d")
        .map_err(|err| CameraError::Backend(js_err(err)))?
        .ok_or_else(|| CameraError::Backend("canvas.getContext('2d') returned null".into()))?
        .dyn_into()
        .map_err(|_| CameraError::Backend("2d context cast failed".into()))?;

    Ok((video, canvas, ctx))
}

fn hide_offscreen(element: &web_sys::Element) {
    let _ = element.set_attribute(
        "style",
        "position:fixed;left:-10000px;top:-10000px;width:1px;height:1px;visibility:hidden;",
    );
}

async fn wait_for_metadata(video: &HtmlVideoElement) -> Result<(), CameraError> {
    if video.ready_state() >= 1 && video.video_width() > 0 {
        return Ok(());
    }

    let promise = js_sys::Promise::new(&mut |resolve, _reject| {
        let closure = Closure::once_into_js(Box::new(move || {
            let _ = resolve.call0(&JsValue::UNDEFINED);
        }) as Box<dyn FnOnce()>);
        video.set_onloadedmetadata(Some(closure.unchecked_ref()));
    });
    JsFuture::from(promise)
        .await
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    Ok(())
}

fn build_constraints(config: &SessionConfig) -> MediaStreamConstraints {
    let video_obj = Object::new();
    let _ = Reflect::set(
        &video_obj,
        &"deviceId".into(),
        &JsValue::from_str(&config.device_id),
    );
    if let Some(res) = config.resolution {
        let _ = Reflect::set(
            &video_obj,
            &"width".into(),
            &JsValue::from_f64(res.width.into()),
        );
        let _ = Reflect::set(
            &video_obj,
            &"height".into(),
            &JsValue::from_f64(res.height.into()),
        );
    }
    if let Some(fps) = config.target_fps {
        let _ = Reflect::set(
            &video_obj,
            &"frameRate".into(),
            &JsValue::from_f64(fps.into()),
        );
    }

    let constraints = MediaStreamConstraints::new();
    constraints.set_video(&video_obj);
    constraints
}

fn first_video_track(stream: &MediaStream) -> Option<MediaStreamTrack> {
    let tracks = stream.get_video_tracks();
    if tracks.length() == 0 {
        return None;
    }
    tracks.get(0).dyn_into().ok()
}

fn stop_tracks(stream: &MediaStream) {
    let tracks = stream.get_tracks();
    for i in 0..tracks.length() {
        if let Ok(track) = tracks.get(i).dyn_into::<MediaStreamTrack>() {
            track.stop();
        }
    }
}

// -------------------------------------------------------------------
// Frame pump
// -------------------------------------------------------------------

fn make_pump(
    video: HtmlVideoElement,
    ctx: CanvasRenderingContext2d,
    width: u32,
    height: u32,
    pixel_format: PixelFormat,
    tx: flume::Sender<CameraFrame>,
    dropped: Rc<AtomicU64>,
    seq: Rc<AtomicU64>,
) -> Closure<dyn FnMut()> {
    Closure::wrap(Box::new(move || {
        if video.ready_state() < 2 {
            return;
        }
        let bytes = match read_frame(&ctx, &video, width, height) {
            Ok(mut bytes) => {
                if matches!(pixel_format, PixelFormat::Bgra8) {
                    swap_rb_in_place(&mut bytes);
                }
                bytes
            }
            Err(_) => {
                dropped.fetch_add(1, Ordering::Relaxed);
                return;
            }
        };

        let plane = FramePlane {
            offset: 0,
            row_stride: width * 4,
            pixel_stride: 4,
            width,
            height,
        };
        let frame = CameraFrame {
            seq: seq.fetch_add(1, Ordering::Relaxed),
            timestamp_ns: now_ns(),
            resolution: Resolution { width, height },
            rotation_degrees: 0,
            pixel_format,
            planes: vec![plane],
            bytes,
            dropped_before: dropped.swap(0, Ordering::Relaxed) as u32,
        };

        if tx.try_send(frame).is_err() {
            dropped.fetch_add(1, Ordering::Relaxed);
        }
    }) as Box<dyn FnMut()>)
}

fn read_frame(
    ctx: &CanvasRenderingContext2d,
    video: &HtmlVideoElement,
    width: u32,
    height: u32,
) -> Result<Vec<u8>, CameraError> {
    ctx.draw_image_with_html_video_element_and_dw_and_dh(
        video,
        0.0,
        0.0,
        f64::from(width),
        f64::from(height),
    )
    .map_err(|err| CameraError::Backend(js_err(err)))?;
    let image_data = ctx
        .get_image_data(0.0, 0.0, f64::from(width), f64::from(height))
        .map_err(|err| CameraError::Backend(js_err(err)))?;
    Ok(image_data.data().0)
}

fn swap_rb_in_place(bytes: &mut [u8]) {
    for px in bytes.chunks_exact_mut(4) {
        px.swap(0, 2);
    }
}

fn guess_facing(label: &str) -> CameraFacing {
    let lower = label.to_ascii_lowercase();
    if lower.contains("front") || lower.contains("user") {
        CameraFacing::Front
    } else if lower.contains("back") || lower.contains("rear") || lower.contains("environment") {
        CameraFacing::Back
    } else {
        CameraFacing::Unknown
    }
}

fn classify_get_user_media_error(err: JsValue) -> CameraError {
    let msg = js_err(err);
    if msg.contains("NotAllowed") || msg.contains("Permission") {
        CameraError::PermissionDenied
    } else if msg.contains("NotFound") || msg.contains("DevicesNotFound") {
        CameraError::DeviceNotFound(String::new())
    } else if msg.contains("OverconstrainedError") || msg.contains("NotSupported") {
        CameraError::FormatUnsupported
    } else {
        CameraError::Backend(msg)
    }
}

fn js_err(err: JsValue) -> String {
    err.as_string()
        .or_else(|| js_sys::JSON::stringify(&err).ok().map(Into::into))
        .unwrap_or_else(|| "unknown JS error".into())
}

fn now_ns() -> u64 {
    let now = web_sys::window()
        .and_then(|w| w.performance())
        .map_or(0.0, |p| p.now());
    (now * 1_000_000.0) as u64
}
