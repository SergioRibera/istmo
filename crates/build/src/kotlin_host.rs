//! Kotlin host-side (native-hosted) dispatcher generator.
//!
//! Emits three siblings per plugin contract:
//!
//! * `<T>Backend` interface — the platform-facing surface. One method per
//!   trait method. User hand-writes an impl with the SDK-specific body
//!   (Activity / Context / SDK library calls) — no bincode, no wire concern.
//! * `<T>Codecs` interface — reader / writer per `Named` type used in the
//!   contract's signatures. User provides one impl; each entry is typically
//!   a short delegate to a `companion object` helper on the type itself.
//! * `<T>Dispatcher` class — implements `PluginHandler`, decodes inbound
//!   wire bytes, invokes `<T>Backend`, encodes the response. Registered
//!   with `IstmoRuntime.registerHandler(PLUGIN_ID, dispatcher)`.
//!
//! For `#[istmo::plugin(init = Config)]` contracts a `<T>Factory` interface
//! is emitted (user hand-writes one instance per plugin instance) and the
//! dispatcher's `handleCreateInstance` decodes the config, invokes the
//! factory and returns the freshly allocated backend under the caller's
//! `InstanceId`. Backend lookup is via an internal `ConcurrentHashMap`
//! keyed by `InstanceId`.
//!
//! Domain-error methods (`Result<T, E>` in the trait) are wrapped in a
//! `try` block: `BackendException<E>` thrown by the backend surfaces as
//! `PluginException(bytes)` on the wire, and the Rust client sees
//! `IstmoError::PluginError { bytes }`.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::contract::{Contract, Method, MethodKind, TypeRef};

/// Renders the Kotlin host dispatcher for `contract`.
#[must_use]
pub fn generate_kotlin_host(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    write_backend_interface(&mut out, contract);
    let _ = writeln!(out);
    write_codecs_interface(&mut out, contract);
    let _ = writeln!(out);
    write_dispatcher_class(&mut out, contract);
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
    let _ = writeln!(out, "import java.io.ByteArrayOutputStream");
    let _ = writeln!(out);
}

fn write_backend_interface(out: &mut String, contract: &Contract) {
    let _ = writeln!(
        out,
        "/// Platform-facing surface for the `{}` plugin. Hand-write an",
        contract.type_name,
    );
    let _ = writeln!(
        out,
        "/// impl with the SDK-specific logic; the dispatcher below handles",
    );
    let _ = writeln!(out, "/// wire encode/decode.");
    let _ = writeln!(out, "interface {}Backend {{", contract.type_name);
    for (i, method) in contract.methods.iter().enumerate() {
        if i > 0 {
            let _ = writeln!(out);
        }
        write_backend_method(out, method);
    }
    let _ = writeln!(out, "}}");
}

fn write_backend_method(out: &mut String, method: &Method) {
    let args = format_backend_args(method);
    let ret = method.returns.to_kotlin();
    let throws = method
        .error
        .as_ref()
        .map(|e| {
            format!(
                "  // Throw BackendException<{}> for domain errors.",
                e.to_kotlin()
            )
        })
        .unwrap_or_default();
    match method.kind {
        MethodKind::Unary => {
            if !throws.is_empty() {
                let _ = writeln!(out, "   {throws}");
            }
            let _ = writeln!(
                out,
                "    suspend fun {}({args}): {ret}",
                method.name,
            );
        }
        MethodKind::Stream => {
            let _ = writeln!(
                out,
                "    fun {}({args}): kotlinx.coroutines.flow.Flow<{ret}>",
                method.name,
            );
        }
    }
}

fn format_backend_args(method: &Method) -> String {
    method
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.ty.to_kotlin()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn write_codecs_interface(out: &mut String, contract: &Contract) {
    let types = collect_named_types(contract);
    let _ = writeln!(
        out,
        "/// Reader / writer per `Named` type referenced by the `{}` contract.",
        contract.type_name,
    );
    let _ = writeln!(
        out,
        "/// User provides one impl; each entry typically delegates to a",
    );
    let _ = writeln!(out, "/// companion helper on the type itself.");
    let _ = writeln!(out, "interface {}Codecs {{", contract.type_name);
    if types.is_empty() {
        let _ = writeln!(
            out,
            "    // No named types in this contract; nothing to codegen.",
        );
    } else {
        for (i, ty) in types.iter().enumerate() {
            if i > 0 {
                let _ = writeln!(out);
            }
            let _ = writeln!(
                out,
                "    fun read{ty}(bytes: ByteArray, offset: Int): Bincode.Decoded<{ty}>",
            );
            let _ = writeln!(out, "    fun write{ty}(out: ByteArrayOutputStream, value: {ty})");
        }
    }
    let _ = writeln!(out, "}}");
}

/// Returns every unique `Named` type name referenced by the contract's
/// methods (args, returns, error) and the optional `init` type.
fn collect_named_types(contract: &Contract) -> Vec<String> {
    let mut set = BTreeSet::new();
    for method in &contract.methods {
        for arg in &method.args {
            collect_named(&arg.ty, &mut set);
        }
        collect_named(&method.returns, &mut set);
        if let Some(err) = &method.error {
            collect_named(err, &mut set);
        }
    }
    if let Some(init) = &contract.init {
        collect_named(init, &mut set);
    }
    set.into_iter().collect()
}

fn collect_named(ty: &TypeRef, out: &mut BTreeSet<String>) {
    match ty {
        TypeRef::Named(name) => {
            out.insert(name.clone());
        }
        TypeRef::Vec(inner) | TypeRef::Option(inner) => collect_named(inner, out),
        _ => {}
    }
}

/// `true` when any signature references `NativeHandleId` — dispatcher
/// grows a `HandleReleaser` implementation forwarding to each backend
/// that opts in.
fn uses_native_handles(contract: &Contract) -> bool {
    collect_named_types(contract)
        .iter()
        .any(|n| n == "NativeHandleId")
}

fn write_dispatcher_class(out: &mut String, contract: &Contract) {
    let name = &contract.type_name;
    let _ = writeln!(
        out,
        "/// Decodes wire calls, invokes `{name}Backend`, encodes the response.",
    );
    let _ = writeln!(out, "/// Register with `IstmoRuntime.registerHandler(PLUGIN_ID, dispatcher)`.");

    if contract.init.is_some() {
        write_stateful_dispatcher(out, contract);
    } else {
        write_stateless_dispatcher(out, contract);
    }
}

fn write_stateless_dispatcher(out: &mut String, contract: &Contract) {
    let name = &contract.type_name;
    let bases = if uses_native_handles(contract) {
        "PluginHandler, HandleReleaser"
    } else {
        "PluginHandler"
    };
    let _ = writeln!(
        out,
        "class {name}Dispatcher(",
    );
    let _ = writeln!(out, "    private val backend: {name}Backend,");
    let _ = writeln!(out, "    private val codecs: {name}Codecs,");
    let _ = writeln!(out, ") : {bases} {{");
    let _ = writeln!(out);
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(
        out,
        "        const val PLUGIN_ID = \"{}\"",
        contract.plugin_id,
    );
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    if uses_native_handles(contract) {
        let _ = writeln!(out, "    override fun releaseNativeHandle(handleId: Long) {{");
        let _ = writeln!(
            out,
            "        (backend as? HandleReleaser)?.releaseNativeHandle(handleId)",
        );
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);
    }
    write_handle_call(out, contract, /*stateful=*/ false);
    let _ = writeln!(out, "}}");
}

fn write_stateful_dispatcher(out: &mut String, contract: &Contract) {
    let name = &contract.type_name;
    let Some(init) = &contract.init else {
        return;
    };
    let init_kt = init.to_kotlin();
    let _ = writeln!(out, "interface {name}Factory {{");
    let _ = writeln!(
        out,
        "    suspend fun create(config: {init_kt}): {name}Backend",
    );
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let bases = if uses_native_handles(contract) {
        "PluginHandler, HandleReleaser"
    } else {
        "PluginHandler"
    };
    let _ = writeln!(out, "class {name}Dispatcher(");
    let _ = writeln!(out, "    private val factory: {name}Factory,");
    let _ = writeln!(out, "    private val codecs: {name}Codecs,");
    let _ = writeln!(out, ") : {bases} {{");
    let _ = writeln!(out);
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(
        out,
        "        const val PLUGIN_ID = \"{}\"",
        contract.plugin_id,
    );
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    private val instances = java.util.concurrent.ConcurrentHashMap<Long, {name}Backend>()",
    );
    let _ = writeln!(out, "    private val nextInstanceId = java.util.concurrent.atomic.AtomicLong(1)");
    if uses_native_handles(contract) {
        let _ = writeln!(out);
        let _ = writeln!(out, "    override fun releaseNativeHandle(handleId: Long) {{");
        let _ = writeln!(out, "        for (backend in instances.values) {{");
        let _ = writeln!(
            out,
            "            (backend as? HandleReleaser)?.releaseNativeHandle(handleId)",
        );
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    override suspend fun handleCreateInstance(payload: ByteArray): ByteArray {{",
    );
    let _ = writeln!(out, "        var cursor = 0");
    write_read_named(out, "        ", init, "config");
    let _ = writeln!(out, "        val backend = factory.create(config)");
    let _ = writeln!(out, "        val id = nextInstanceId.getAndIncrement()");
    let _ = writeln!(out, "        instances[id] = backend");
    let _ = writeln!(out, "        val out = ByteArrayOutputStream()");
    let _ = writeln!(out, "        Bincode.writeVarintU64(out, id)");
    let _ = writeln!(out, "        return out.toByteArray()");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    write_handle_call(out, contract, /*stateful=*/ true);
    let _ = writeln!(out, "}}");
}

fn write_handle_call(out: &mut String, contract: &Contract, stateful: bool) {
    let name = &contract.type_name;
    let _ = writeln!(
        out,
        "    override suspend fun handleCall(instanceId: Long, method: String, payload: ByteArray): ByteArray {{",
    );
    if stateful {
        let _ = writeln!(out, "        val backend = instances[instanceId]");
        let _ = writeln!(out, "            ?: error(\"{name}: unknown instance $instanceId\")");
    }
    let _ = writeln!(out, "        return when (method) {{");
    for method in &contract.methods {
        write_method_arm(out, method);
    }
    let _ = writeln!(
        out,
        "            else -> error(\"unknown {name} method: $method\")",
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
}

fn write_method_arm(out: &mut String, method: &Method) {
    let has_error = method.error.is_some();
    let _ = writeln!(out, "            \"{}\" -> {{", method.name);
    if has_error {
        let _ = writeln!(out, "                try {{");
    }
    let indent = if has_error { "                    " } else { "                " };
    if !method.args.is_empty() {
        let _ = writeln!(out, "{indent}var cursor = 0");
    }
    let mut arg_names = Vec::with_capacity(method.args.len());
    for arg in &method.args {
        write_read_expr(out, indent, &arg.ty, &arg.name);
        arg_names.push(arg.name.clone());
    }
    let call_args = arg_names.join(", ");
    match method.returns {
        TypeRef::Unit => {
            let _ = writeln!(
                out,
                "{indent}backend.{}({call_args})",
                method.name,
            );
            let _ = writeln!(out, "{indent}ByteArray(0)");
        }
        _ => {
            let _ = writeln!(
                out,
                "{indent}val result = backend.{}({call_args})",
                method.name,
            );
            let _ = writeln!(out, "{indent}val out = ByteArrayOutputStream()");
            write_write_expr(out, indent, &method.returns, "result", "out");
            let _ = writeln!(out, "{indent}out.toByteArray()");
        }
    }
    if has_error {
        let err_ty = method.error.as_ref().unwrap().to_kotlin();
        let _ = writeln!(out, "                }} catch (e: BackendException<*>) {{");
        let _ = writeln!(out, "                    @Suppress(\"UNCHECKED_CAST\")");
        let _ = writeln!(out, "                    val err = e.error as {err_ty}");
        let _ = writeln!(out, "                    val errOut = ByteArrayOutputStream()");
        write_write_expr(out, "                    ", method.error.as_ref().unwrap(), "err", "errOut");
        let _ = writeln!(out, "                    throw PluginException(errOut.toByteArray())");
        let _ = writeln!(out, "                }}");
    }
    let _ = writeln!(out, "            }}");
}

/// Emit a `val <binding> = ...; cursor = ...` snippet decoding `ty` at
/// `cursor` from `payload`.
fn write_read_expr(out: &mut String, indent: &str, ty: &TypeRef, binding: &str) {
    match ty {
        TypeRef::Named(_) => write_read_named(out, indent, ty, binding),
        _ => {
            let reader = read_call(ty);
            let _ = writeln!(
                out,
                "{indent}val d_{binding} = {reader}; cursor = d_{binding}.consumed",
            );
            let _ = writeln!(out, "{indent}val {binding} = d_{binding}.value");
        }
    }
}

fn write_read_named(out: &mut String, indent: &str, ty: &TypeRef, binding: &str) {
    let TypeRef::Named(name) = ty else {
        return;
    };
    let _ = writeln!(
        out,
        "{indent}val d_{binding} = codecs.read{name}(payload, cursor); cursor = d_{binding}.consumed",
    );
    let _ = writeln!(out, "{indent}val {binding} = d_{binding}.value");
}

/// Kotlin conversion suffix for a Long → target integer type.
/// bincode 2 varint u64 always fits in a signed Long via bit-cast; the
/// helper picks the idiomatic `.toX()` extension so the surface type
/// matches the declared trait argument.
fn kt_int_cast(ty: &TypeRef) -> &'static str {
    match ty {
        TypeRef::U8 => ".toUByte()",
        TypeRef::U16 => ".toUShort()",
        TypeRef::U32 => ".toUInt()",
        TypeRef::U64 => ".toULong()",
        TypeRef::I8 => ".toByte()",
        TypeRef::I16 => ".toShort()",
        TypeRef::I32 => ".toInt()",
        TypeRef::I64 => "",
        _ => "",
    }
}

fn read_call(ty: &TypeRef) -> String {
    read_expr(ty, "payload", "cursor")
}

fn read_expr(ty: &TypeRef, bytes: &str, cursor: &str) -> String {
    match ty {
        TypeRef::Bool => format!("Bincode.readBool({bytes}, {cursor})"),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let cast = kt_int_cast(ty);
            format!("Bincode.readVarintU64({bytes}, {cursor}).let {{ Bincode.Decoded(it.first{cast}, it.second) }}")
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let cast = kt_int_cast(ty);
            format!("Bincode.readVarintI64({bytes}, {cursor}).let {{ Bincode.Decoded(it.first{cast}, it.second) }}")
        }
        TypeRef::F32 => format!("Bincode.readF32({bytes}, {cursor})"),
        TypeRef::F64 => format!("Bincode.readF64({bytes}, {cursor})"),
        TypeRef::String => format!("Bincode.readString({bytes}, {cursor})"),
        TypeRef::Bytes => format!("Bincode.readBytes({bytes}, {cursor})"),
        TypeRef::Vec(inner) => {
            let inner_reader = read_expr(inner, "p", "o");
            format!("Bincode.readVec({bytes}, {cursor}) {{ p, o -> {inner_reader} }}")
        }
        TypeRef::Option(inner) => {
            let inner_reader = read_expr(inner, "p", "o");
            format!("Bincode.readOption({bytes}, {cursor}) {{ p, o -> {inner_reader} }}")
        }
        TypeRef::Unit => format!("Bincode.Decoded(Unit, {cursor})"),
        TypeRef::Named(name) => format!("codecs.read{name}({bytes}, {cursor})"),
    }
}

/// Emit lines that write `binding` to `buf` per `ty`. Named types delegate
/// to the codecs interface; primitives / composites use `Bincode.write*`.
fn write_write_expr(out: &mut String, indent: &str, ty: &TypeRef, binding: &str, buf: &str) {
    match ty {
        TypeRef::Named(name) => {
            let _ = writeln!(out, "{indent}codecs.write{name}({buf}, {binding})");
        }
        TypeRef::String => {
            let _ = writeln!(out, "{indent}Bincode.writeString({buf}, {binding})");
        }
        TypeRef::Bool => {
            let _ = writeln!(out, "{indent}Bincode.writeBool({buf}, {binding})");
        }
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVarintU64({buf}, {binding}.toLong())",
            );
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVarintI64({buf}, {binding}.toLong())",
            );
        }
        TypeRef::F32 => {
            let _ = writeln!(out, "{indent}Bincode.writeF32({buf}, {binding})");
        }
        TypeRef::F64 => {
            let _ = writeln!(out, "{indent}Bincode.writeF64({buf}, {binding})");
        }
        TypeRef::Bytes => {
            let _ = writeln!(out, "{indent}Bincode.writeBytes({buf}, {binding})");
        }
        TypeRef::Unit => {
            let _ = writeln!(out, "{indent}// () — nothing to encode");
        }
        TypeRef::Vec(inner) => {
            let inner_writer = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVec({buf}, {binding}) {{ s, v -> {inner_writer} }}",
            );
        }
        TypeRef::Option(inner) => {
            let inner_writer = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeOption({buf}, {binding}) {{ s, v -> {inner_writer} }}",
            );
        }
    }
}

fn write_lambda(ty: &TypeRef) -> String {
    // Body of a `{ s, v -> ... }` closure passed to `Bincode.writeVec` /
    // `writeOption`. `s` is the fresh ByteArrayOutputStream, `v` the value.
    match ty {
        TypeRef::Named(name) => format!("codecs.write{name}(s, v)"),
        TypeRef::String => "Bincode.writeString(s, v)".to_owned(),
        TypeRef::Bool => "Bincode.writeBool(s, v)".to_owned(),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            "Bincode.writeVarintU64(s, v.toLong())".to_owned()
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            "Bincode.writeVarintI64(s, v.toLong())".to_owned()
        }
        TypeRef::F32 => "Bincode.writeF32(s, v)".to_owned(),
        TypeRef::F64 => "Bincode.writeF64(s, v)".to_owned(),
        TypeRef::Bytes => "Bincode.writeBytes(s, v)".to_owned(),
        TypeRef::Unit => "/* () */".to_owned(),
        TypeRef::Vec(inner) => {
            let inner_writer = write_lambda(inner);
            format!("Bincode.writeVec(s, v) {{ ss, vv -> {inner_writer} }}")
        }
        TypeRef::Option(inner) => {
            let inner_writer = write_lambda(inner);
            format!("Bincode.writeOption(s, v) {{ ss, vv -> {inner_writer} }}")
        }
    }
}
