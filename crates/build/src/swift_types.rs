use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::codegen::{
    NamedAccess, SwiftNames, SwiftWire, local, swift_ident, swift_label, write_header,
};
use crate::contract::{Contract, EnumDef, SharedTypes, StructDef, TypeDef, TypeRef};

/// Locals a struct reader declares before decoding its fields.
const READER_LOCALS: &[&str] = &["c"];

#[must_use]
pub fn generate_swift_types(contract: &Contract) -> String {
    let errors = error_type_names(contract);
    let mut out = String::new();
    write_header(&mut out, contract);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    if contract.references_native_handle() {
        // `NativeHandleId` is declared by the runtime module.
        let _ = writeln!(out, "import IstmoRuntime");
    }
    let names = SwiftNames::of(contract).within();
    write_namespace(
        &mut out,
        names,
        &format!("The `{}` plugin's message types.", contract.type_name),
        contract.types.iter().map(|ty| {
            let is_error = is_error_shape(ty.name()) || errors.contains(ty.name());
            (ty, is_error)
        }),
    );
    out
}

/// The declarations of a shared group's types, one Swift file per group,
/// nested in the group's namespace. No codecs: every plugin's
/// `CodecsImpl` reads and writes the shared types it uses.
#[must_use]
pub fn generate_swift_shared_types(group: &SharedTypes) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// shared types: {}", group.group);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    let mut handles = false;
    for ty in &group.types {
        let refs: Vec<&TypeRef> = match ty {
            TypeDef::Struct(s) => s.fields.iter().map(|f| &f.ty).collect(),
            TypeDef::Enum(e) => e.variants.iter().flat_map(|v| v.payload.iter()).collect(),
        };
        for r in refs {
            r.for_each_named(&mut |name| handles |= name == crate::codegen::NATIVE_HANDLE_ID);
        }
    }
    if handles {
        let _ = writeln!(out, "import IstmoRuntime");
    }
    write_namespace(
        &mut out,
        SwiftNames::of_group(group),
        &format!("Message types shared by plugins: `{}`.", group.group),
        group.types.iter().map(|ty| (ty, is_error_shape(ty.name()))),
    );
    out
}

/// `public enum <Namespace> {}` and an extension nesting each type in it.
fn write_namespace<'a>(
    out: &mut String,
    names: SwiftNames<'_>,
    doc: &str,
    types: impl Iterator<Item = (&'a TypeDef, bool)>,
) {
    let namespace = names.namespace();
    let _ = writeln!(out);
    let _ = writeln!(out, "/// {doc}");
    let _ = writeln!(out, "public enum {namespace} {{}}");
    let mut body = String::new();
    for (ty, is_error) in types {
        if !body.is_empty() {
            body.push('\n');
        }
        match ty {
            TypeDef::Struct(s) => write_struct(&mut body, names, s, is_error),
            TypeDef::Enum(e) => write_enum(&mut body, names, e, is_error),
        }
    }
    if body.is_empty() {
        return;
    }
    let _ = writeln!(out);
    let _ = writeln!(out, "extension {namespace} {{");
    for line in body.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "    {line}");
        }
    }
    let _ = writeln!(out, "}}");
}

#[must_use]
pub fn generate_swift_codecs(contract: &Contract) -> String {
    let names = SwiftNames::of(contract);
    let wire = SwiftWire::new(NamedAccess::SelfImpl, names);
    let mut out = String::new();
    write_header(&mut out, contract);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out, "import IstmoRuntime");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "public final class {}CodecsImpl: {}Codecs {{",
        contract.type_name, contract.type_name,
    );
    let _ = writeln!(out, "    public init() {{}}");
    for ty in contract.codec_types() {
        let _ = writeln!(out);
        match ty {
            TypeDef::Struct(s) => write_struct_codec(&mut out, wire, names, s),
            TypeDef::Enum(e) => write_enum_codec(&mut out, wire, names, e),
        }
    }
    if contract.references_native_handle() {
        let _ = writeln!(out);
        write_native_handle_codec(&mut out);
    }
    let _ = writeln!(out, "}}");
    out
}

/// Declared types some method throws: they must conform to `Error` for
/// the dispatcher's `catch let err as T` and the client's `throw`.
fn error_type_names(contract: &Contract) -> BTreeSet<&str> {
    contract
        .error_types()
        .into_iter()
        .filter_map(|ty| match ty {
            TypeRef::Named(name) => Some(name.as_str()),
            _ => None,
        })
        .collect()
}

fn write_struct(out: &mut String, names: SwiftNames<'_>, s: &StructDef, is_error: bool) {
    // `Error` refines `Sendable`; plain types state it, so backends can
    // capture them in `@Sendable` capture callbacks (Swift 6 mode).
    let conform = if is_error { ": Error" } else { ": Sendable" };
    let _ = writeln!(out, "public struct {}{conform} {{", s.name);
    for f in &s.fields {
        let _ = writeln!(
            out,
            "    public let {}: {}",
            swift_ident(&f.name),
            names.ty(&f.ty)
        );
    }
    let _ = writeln!(out);
    let init_args = s
        .fields
        .iter()
        .map(|f| format!("{}: {}", swift_ident(&f.name), names.ty(&f.ty)))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(out, "    public init({init_args}) {{");
    for f in &s.fields {
        let name = swift_ident(&f.name);
        let _ = writeln!(out, "        self.{name} = {name}");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
}

fn write_enum(out: &mut String, names: SwiftNames<'_>, e: &EnumDef, is_error: bool) {
    if e.variants.iter().all(|v| v.payload.is_empty()) {
        let conform = if is_error { ", Error" } else { ", Sendable" };
        let _ = writeln!(out, "public enum {}: UInt32{conform} {{", e.name);
        for (i, v) in e.variants.iter().enumerate() {
            let _ = writeln!(out, "    case {} = {i}", to_swift_case(&v.name));
        }
    } else {
        let conform = if is_error { ": Error" } else { ": Sendable" };
        let _ = writeln!(out, "public enum {}{conform} {{", e.name);
        for v in &e.variants {
            let case_name = to_swift_case(&v.name);
            if v.payload.is_empty() {
                let _ = writeln!(out, "    case {case_name}");
            } else {
                let tys = v
                    .payload
                    .iter()
                    .map(|ty| names.ty(ty))
                    .collect::<Vec<_>>()
                    .join(", ");
                let _ = writeln!(out, "    case {case_name}({tys})");
            }
        }
    }
    let _ = writeln!(out, "}}");
}

fn is_error_shape(name: &str) -> bool {
    name.ends_with("Error")
}

/// Swift case names are lowerCamelCase.
fn to_swift_case(name: &str) -> String {
    let mut chars = name.chars();
    let Some(first) = chars.next() else {
        return String::new();
    };
    let base = first.to_lowercase().collect::<String>() + chars.as_str();
    swift_ident(&base)
}

fn write_struct_codec(out: &mut String, wire: SwiftWire<'_>, names: SwiftNames<'_>, s: &StructDef) {
    let ty = names.named(&s.name);
    let _ = writeln!(
        out,
        "    public func read{}(_ c: inout Bincode.Cursor) throws -> {} {{",
        s.name, ty,
    );
    let mut init_args = Vec::with_capacity(s.fields.len());
    for f in &s.fields {
        let label = swift_label(&f.name);
        // A `()` field occupies no wire bytes; binding it to a local
        // draws swiftc's "inferred to have type '()'" warning.
        if f.ty.is_unit() {
            init_args.push(format!("{label}: ()"));
            continue;
        }
        let name = local(&f.name, READER_LOCALS, swift_ident);
        let _ = writeln!(out, "        let {name} = {}", wire.read(&f.ty, "c"));
        init_args.push(format!("{label}: {name}"));
    }
    let _ = writeln!(out, "        return {ty}({})", init_args.join(", "));
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "    public func write{}(_ out: inout Data, _ value: {}) {{",
        s.name, ty,
    );
    for f in &s.fields {
        let value = format!("value.{}", swift_ident(&f.name));
        wire.write_stmt(out, "        ", &f.ty, "out", &value);
    }
    let _ = writeln!(out, "    }}");
}

fn write_enum_codec(out: &mut String, wire: SwiftWire<'_>, names: SwiftNames<'_>, e: &EnumDef) {
    let ty = names.named(&e.name);
    let has_payload = e.variants.iter().any(|v| !v.payload.is_empty());

    let _ = writeln!(
        out,
        "    public func read{}(_ c: inout Bincode.Cursor) throws -> {} {{",
        e.name, ty,
    );
    let _ = writeln!(out, "        let disc = try Bincode.readVarintU32(&c)");
    if has_payload {
        let _ = writeln!(out, "        switch disc {{");
        for (i, v) in e.variants.iter().enumerate() {
            let case_name = to_swift_case(&v.name);
            match v.payload.as_slice() {
                [] => {
                    let _ = writeln!(out, "        case {i}: return .{case_name}");
                }
                [ty] => {
                    let _ = writeln!(
                        out,
                        "        case {i}: return .{case_name}({})",
                        wire.read(ty, "c")
                    );
                }
                payload => {
                    let _ = writeln!(out, "        case {i}:");
                    let mut bindings = Vec::with_capacity(payload.len());
                    for (idx, ty) in payload.iter().enumerate() {
                        let name = format!("f{idx}");
                        let _ = writeln!(out, "            let {name} = {}", wire.read(ty, "c"));
                        bindings.push(name);
                    }
                    let _ = writeln!(
                        out,
                        "            return .{case_name}({})",
                        bindings.join(", ")
                    );
                }
            }
        }
        let _ = writeln!(
            out,
            "        default: throw Bincode.DecodeError.invalidTag(UInt8(clamping: disc))",
        );
        let _ = writeln!(out, "        }}");
    } else {
        let _ = writeln!(
            out,
            "        guard let value = {ty}(rawValue: disc) else {{",
        );
        let _ = writeln!(
            out,
            "            throw Bincode.DecodeError.invalidTag(UInt8(clamping: disc))",
        );
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "        return value");
    }
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);

    let _ = writeln!(
        out,
        "    public func write{}(_ out: inout Data, _ value: {}) {{",
        e.name, ty,
    );
    if has_payload {
        let _ = writeln!(out, "        switch value {{");
        for (i, v) in e.variants.iter().enumerate() {
            let case_name = to_swift_case(&v.name);
            match v.payload.as_slice() {
                [] => {
                    let _ = writeln!(out, "        case .{case_name}:");
                    let _ = writeln!(out, "            Bincode.writeVarintU32(&out, {i})");
                }
                [ty] => {
                    let _ = writeln!(out, "        case .{case_name}(let payload):");
                    let _ = writeln!(out, "            Bincode.writeVarintU32(&out, {i})");
                    wire.write_stmt(out, "            ", ty, "out", "payload");
                }
                payload => {
                    let bindings = (0..payload.len())
                        .map(|idx| format!("let f{idx}"))
                        .collect::<Vec<_>>()
                        .join(", ");
                    let _ = writeln!(out, "        case .{case_name}({bindings}):");
                    let _ = writeln!(out, "            Bincode.writeVarintU32(&out, {i})");
                    for (idx, ty) in payload.iter().enumerate() {
                        wire.write_stmt(out, "            ", ty, "out", &format!("f{idx}"));
                    }
                }
            }
        }
        let _ = writeln!(out, "        }}");
    } else {
        let _ = writeln!(out, "        Bincode.writeVarintU32(&out, value.rawValue)");
    }
    let _ = writeln!(out, "    }}");
}

fn write_native_handle_codec(out: &mut String) {
    let _ = writeln!(
        out,
        "    public func readNativeHandleId(_ c: inout Bincode.Cursor) throws -> NativeHandleId {{",
    );
    let _ = writeln!(out, "        return try Bincode.readVarintU64(&c)");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    public func writeNativeHandleId(_ out: inout Data, _ value: NativeHandleId) {{",
    );
    let _ = writeln!(out, "        Bincode.writeVarintU64(&out, value)");
    let _ = writeln!(out, "    }}");
}
