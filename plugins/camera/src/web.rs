//! Browser host for the camera plugin.
//!
//! Pure wasm32-unknown-unknown — talks to `navigator.mediaDevices`
//! directly through `web-sys`. Enabled with the `web` feature.
//!
//! # Pipeline
//!
//! - [`Camera::devices`] walks `navigator.mediaDevices.enumerateDevices()`
//!   and filters `kind == "videoinput"`.
//! - [`Camera::request_access`] opens a short-lived stream with
//!   `getUserMedia({ video: true })` and immediately stops the tracks,
//!   driving the browser's permission prompt.
//! - [`Camera::open`] opens the real `MediaStream`, attaches it to an
//!   invisible `<video>` element, and starts a `setInterval`-driven
//!   frame pump that `drawImage`s the video into a hidden `<canvas>`
//!   and ships the resulting `Uint8ClampedArray` RGBA bytes through a
//!   bounded `flume::Receiver<CameraFrame>`.
//! - [`Camera::close`] stops every track on the stream, clears the
//!   interval, and drops the DOM elements.
//!
//! # Thread safety
//!
//! `MediaStream`, `HtmlVideoElement`, `HtmlCanvasElement`, and
//! `CanvasRenderingContext2d` are `!Send` + `!Sync`. The plugin trait
//! generated by `istmo-macros` requires `Dispatch: Send + Sync +
//! 'static` and `async fn` return types that are `Send`. We satisfy
//! those bounds through `send_wrapper::SendWrapper`, which is sound
//! on `wasm32-unknown-unknown` because the target is single-threaded.
//! Every `.await` is driven by `wasm_bindgen_futures::spawn_local`
//! and the result is relayed through a `flume::Receiver` — the outer
//! `async fn` only waits on a `Send` channel. If this code is ever
//! ported to wasm threads, the `SendWrapper` boundaries need to be
//! re-evaluated.
//!
//! # Supported pixel formats
//!
//! The canvas pump produces RGBA. [`PixelFormat::Rgba8`] passes
//! through; [`PixelFormat::Bgra8`] swaps R↔B in place. Every other
//! format returns [`CameraError::FormatUnsupported`] on `open`.

#![cfg(all(target_arch = "wasm32", feature = "web"))]

