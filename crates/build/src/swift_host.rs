//! Swift host-side (native-hosted) dispatcher generator.
//!
//! Emits three siblings per plugin contract:
//!
//! * `<T>Backend` protocol — platform-facing surface. User hand-writes an
//!   impl carrying the iOS SDK-specific logic; no bincode / wire concern.
//! * `<T>Codecs` protocol — reader / writer per `Named` type used in the
//!   contract's signatures. User provides one impl; each entry typically
//!   delegates to a helper on the type itself.
//! * `<T>Dispatcher` class — implements `PluginHandler`, decodes inbound
//!   wire bytes, invokes the backend, encodes the response.
//!
//! For `#[istmo::plugin(init = Config)]` contracts a `<T>Factory` protocol
//! is emitted and the dispatcher's `handleCreateInstance` decodes the
//! config, invokes the factory and returns a fresh `InstanceId`. Backends
//! are cached in a `[UInt64: <T>Backend]` dictionary.
//!
//! Domain-error methods (`Result<T, E>` in the trait) are wrapped in
//! `do { ... } catch let err as E { ... }`: a typed throw from the
//! backend surfaces as `PluginException(payload)` on the wire, and the
//! Rust client sees `IstmoError::PluginError { bytes }`.

use std::collections::BTreeSet;
use std::fmt::Write as _;

use crate::contract::{Contract, Method, MethodKind, TypeRef};

/// Renders the Swift host dispatcher for `contract`.
#[must_use]
pub fn generate_swift_host(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    write_backend_protocol(&mut out, contract);
    let _ = writeln!(out);
    write_codecs_protocol(&mut out, contract);
    let _ = writeln!(out);
    write_dispatcher_class(&mut out, contract);
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
    let _ = writeln!(out, "import Foundation");
    let _ = writeln!(out);
}

fn write_backend_protocol(out: &mut String, contract: &Contract) {
    let _ = writeln!(
        out,
        "/// Platform-facing surface for the `{}` plugin. Hand-write an",
        contract.type_name,
    );
    let _ = writeln!(
        out,
        "/// impl with the SDK-specific logic; the dispatcher below handles",
    );
    let _ = writeln!(out, "/// wire encode/decode.");
    let _ = writeln!(out, "public protocol {}Backend: AnyObject {{", contract.type_name);
    for method in &contract.methods {
        write_backend_method(out, method);
    }
    let _ = writeln!(out, "}}");
}

fn write_backend_method(out: &mut String, method: &Method) {
    let args = format_backend_args(method);
    let ret = swift_return(&method.returns);
    match method.kind {
        MethodKind::Unary => {
            if let Some(err) = &method.error {
                let _ = writeln!(
                    out,
                    "    /// Throw `{}` to surface a typed domain error.",
                    err.to_swift()
                );
            }
            let _ = writeln!(
                out,
                "    func {}({args}) async throws -> {ret}",
                method.name,
            );
        }
        MethodKind::Stream => {
            let _ = writeln!(
                out,
                "    func {}({args}) -> AsyncThrowingStream<{ret}, Error>",
                method.name,
            );
        }
    }
}

fn format_backend_args(method: &Method) -> String {
    method
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.ty.to_swift()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn swift_return(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Unit => "Void".to_owned(),
        _ => ty.to_swift(),
    }
}

fn write_codecs_protocol(out: &mut String, contract: &Contract) {
    let types = collect_codec_types(contract);
    let _ = writeln!(
        out,
        "/// Reader / writer per `Named` type referenced by the `{}` contract.",
        contract.type_name,
    );
    let _ = writeln!(
        out,
        "/// User provides one impl; each entry typically delegates to a",
    );
    let _ = writeln!(out, "/// helper on the type itself.");
    let _ = writeln!(out, "public protocol {}Codecs {{", contract.type_name);
    if types.is_empty() {
        let _ = writeln!(out, "    // No named types in this contract.");
    } else {
        for ty in &types {
            let _ = writeln!(out, "    func read{ty}(_ c: inout Bincode.Cursor) throws -> {ty}");
            let _ = writeln!(out, "    func write{ty}(_ out: inout Data, _ value: {ty})");
        }
    }
    let _ = writeln!(out, "}}");
}

/// See kotlin_host::collect_codec_types — same logic.
fn collect_codec_types(contract: &Contract) -> Vec<String> {
    let mut set: BTreeSet<String> = collect_named_types(contract).into_iter().collect();
    for def in &contract.types {
        set.insert(def.name().to_owned());
    }
    set.into_iter().collect()
}

fn collect_named_types(contract: &Contract) -> Vec<String> {
    let mut set = BTreeSet::new();
    for method in &contract.methods {
        for arg in &method.args {
            collect_named(&arg.ty, &mut set);
        }
        collect_named(&method.returns, &mut set);
        if let Some(err) = &method.error {
            collect_named(err, &mut set);
        }
    }
    if let Some(init) = &contract.init {
        collect_named(init, &mut set);
    }
    set.into_iter().collect()
}

fn collect_named(ty: &TypeRef, out: &mut BTreeSet<String>) {
    match ty {
        TypeRef::Named(name) => {
            out.insert(name.clone());
        }
        TypeRef::Vec(inner) | TypeRef::Option(inner) => collect_named(inner, out),
        _ => {}
    }
}

/// Returns `true` when any signature in the contract references
/// `NativeHandleId` — signal that the dispatcher should also conform to
/// `HandleReleaser` and forward `releaseNativeHandle` to backends.
fn uses_native_handles(contract: &Contract) -> bool {
    collect_named_types(contract)
        .iter()
        .any(|n| n == "NativeHandleId")
}

fn write_dispatcher_class(out: &mut String, contract: &Contract) {
    let name = &contract.type_name;
    let _ = writeln!(
        out,
        "/// Decodes wire calls, invokes `{name}Backend`, encodes the response.",
    );
    let _ = writeln!(out, "/// Register with `IstmoRuntime.shared.registerHandler(PLUGIN_ID, dispatcher)`.");

    if contract.init.is_some() {
        write_stateful_dispatcher(out, contract);
    } else {
        write_stateless_dispatcher(out, contract);
    }
}

fn write_stateless_dispatcher(out: &mut String, contract: &Contract) {
    let name = &contract.type_name;
    let releaser = if uses_native_handles(contract) {
        ", HandleReleaser"
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "public final class {name}Dispatcher: PluginHandler{releaser} {{",
    );
    let _ = writeln!(
        out,
        "    public static let PLUGIN_ID: String = \"{}\"",
        contract.plugin_id,
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "    private let backend: {name}Backend");
    let _ = writeln!(out, "    private let codecs: {name}Codecs");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    public init(backend: {name}Backend, codecs: {name}Codecs) {{",
    );
    let _ = writeln!(out, "        self.backend = backend");
    let _ = writeln!(out, "        self.codecs = codecs");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    if uses_native_handles(contract) {
        let _ = writeln!(
            out,
            "    public func releaseNativeHandle(_ handleId: UInt64) {{",
        );
        let _ = writeln!(
            out,
            "        (backend as? HandleReleaser)?.releaseNativeHandle(handleId)",
        );
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);
    }
    write_handle_call(out, contract, /*stateful=*/ false);
    let _ = writeln!(out, "}}");
}

fn write_stateful_dispatcher(out: &mut String, contract: &Contract) {
    let name = &contract.type_name;
    let Some(init) = &contract.init else {
        return;
    };
    let init_sw = init.to_swift();
    let _ = writeln!(out, "public protocol {name}Factory {{");
    let _ = writeln!(
        out,
        "    func create(config: {init_sw}) async throws -> {name}Backend",
    );
    let _ = writeln!(out, "}}");
    let _ = writeln!(out);
    let releaser = if uses_native_handles(contract) {
        ", HandleReleaser"
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "public final class {name}Dispatcher: PluginHandler{releaser} {{",
    );
    let _ = writeln!(
        out,
        "    public static let PLUGIN_ID: String = \"{}\"",
        contract.plugin_id,
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "    private let factory: {name}Factory");
    let _ = writeln!(out, "    private let codecs: {name}Codecs");
    let _ = writeln!(out, "    private var instances: [UInt64: {name}Backend] = [:]");
    let _ = writeln!(out, "    private var nextInstanceId: UInt64 = 1");
    let _ = writeln!(out, "    private let lock = NSLock()");
    let _ = writeln!(out);
    if uses_native_handles(contract) {
        let _ = writeln!(
            out,
            "    public func releaseNativeHandle(_ handleId: UInt64) {{",
        );
        let _ = writeln!(out, "        lock.lock()");
        let _ = writeln!(out, "        let snapshot = Array(instances.values)");
        let _ = writeln!(out, "        lock.unlock()");
        let _ = writeln!(out, "        for backend in snapshot {{");
        let _ = writeln!(
            out,
            "            (backend as? HandleReleaser)?.releaseNativeHandle(handleId)",
        );
        let _ = writeln!(out, "        }}");
        let _ = writeln!(out, "    }}");
        let _ = writeln!(out);
    }
    let _ = writeln!(
        out,
        "    public init(factory: {name}Factory, codecs: {name}Codecs) {{",
    );
    let _ = writeln!(out, "        self.factory = factory");
    let _ = writeln!(out, "        self.codecs = codecs");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    public func handleCreateInstance(payload: Data) async throws -> Data {{",
    );
    let _ = writeln!(out, "        var c = Bincode.Cursor(payload)");
    write_read_named(out, "        ", init, "config");
    let _ = writeln!(out, "        let backend = try await factory.create(config: config)");
    let _ = writeln!(out, "        lock.lock()");
    let _ = writeln!(out, "        let id = nextInstanceId");
    let _ = writeln!(out, "        nextInstanceId += 1");
    let _ = writeln!(out, "        instances[id] = backend");
    let _ = writeln!(out, "        lock.unlock()");
    let _ = writeln!(out, "        var out = Data()");
    let _ = writeln!(out, "        Bincode.writeVarintU64(&out, id)");
    let _ = writeln!(out, "        return out");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    write_handle_call(out, contract, /*stateful=*/ true);
    let _ = writeln!(out, "}}");
}

// (write_handle_call and write_method_arm handle both stateless and
// stateful paths.)

fn write_handle_call(out: &mut String, contract: &Contract, stateful: bool) {
    let name = &contract.type_name;
    let _ = writeln!(
        out,
        "    public func handleCall(instanceId: UInt64, method: String, payload: Data) async throws -> Data {{",
    );
    if stateful {
        let _ = writeln!(out, "        lock.lock()");
        let _ = writeln!(out, "        let backendOpt = instances[instanceId]");
        let _ = writeln!(out, "        lock.unlock()");
        let _ = writeln!(
            out,
            "        guard let backend = backendOpt else {{ throw PluginRuntimeError.unknownInstance(instanceId) }}",
        );
    }
    let _ = writeln!(out, "        switch method {{");
    for method in &contract.methods {
        write_method_arm(out, method);
    }
    let _ = writeln!(out, "        default:");
    let _ = writeln!(
        out,
        "            throw PluginRuntimeError.unknownMethod(plugin: \"{}\", method: method)",
        name,
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
}

fn write_method_arm(out: &mut String, method: &Method) {
    let has_error = method.error.is_some();
    let _ = writeln!(out, "        case \"{}\":", method.name);
    if has_error {
        let _ = writeln!(out, "            do {{");
    }
    let indent = if has_error { "                " } else { "            " };
    if !method.args.is_empty() {
        let _ = writeln!(out, "{indent}var c = Bincode.Cursor(payload)");
    }
    for arg in &method.args {
        write_read_expr(out, indent, &arg.ty, &arg.name);
    }
    let call_args: String = method
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.name))
        .collect::<Vec<_>>()
        .join(", ");
    match method.returns {
        TypeRef::Unit => {
            let _ = writeln!(
                out,
                "{indent}try await backend.{}({call_args})",
                method.name,
            );
            let _ = writeln!(out, "{indent}return Data()");
        }
        _ => {
            let _ = writeln!(
                out,
                "{indent}let result = try await backend.{}({call_args})",
                method.name,
            );
            let _ = writeln!(out, "{indent}var out = Data()");
            write_write_expr(out, indent, &method.returns, "result", "out");
            let _ = writeln!(out, "{indent}return out");
        }
    }
    if has_error {
        let err_ty = method.error.as_ref().unwrap().to_swift();
        let _ = writeln!(out, "            }} catch let err as {err_ty} {{");
        let _ = writeln!(out, "                var errOut = Data()");
        write_write_expr(out, "                ", method.error.as_ref().unwrap(), "err", "errOut");
        let _ = writeln!(out, "                throw PluginException(payload: errOut)");
        let _ = writeln!(out, "            }}");
    }
}

fn write_read_expr(out: &mut String, indent: &str, ty: &TypeRef, binding: &str) {
    match ty {
        TypeRef::Named(_) => write_read_named(out, indent, ty, binding),
        _ => {
            let call = read_call(ty);
            let _ = writeln!(out, "{indent}let {binding} = {call}");
        }
    }
}

fn write_read_named(out: &mut String, indent: &str, ty: &TypeRef, binding: &str) {
    let TypeRef::Named(name) = ty else {
        return;
    };
    let _ = writeln!(out, "{indent}let {binding} = try codecs.read{name}(&c)");
}

fn read_call(ty: &TypeRef) -> String {
    read_expr(ty, "c")
}

/// Reader expression using `cursor_name` as the buffer variable. Emitted
/// verbatim into the source — the caller must have declared it as
/// `var <cursor_name> = Bincode.Cursor(payload)` or a closure parameter.
fn read_expr(ty: &TypeRef, cursor: &str) -> String {
    match ty {
        TypeRef::Bool => format!("try Bincode.readBool(&{cursor})"),
        TypeRef::U8 => format!("try Bincode.readU8(&{cursor})"),
        TypeRef::I8 => format!("Int8(bitPattern: try Bincode.readU8(&{cursor}))"),
        TypeRef::U16 => format!("UInt16(try Bincode.readVarintU64(&{cursor}))"),
        TypeRef::I16 => format!("Int16(try Bincode.readVarintI64(&{cursor}))"),
        TypeRef::U32 => format!("try Bincode.readVarintU32(&{cursor})"),
        TypeRef::I32 => format!("try Bincode.readVarintI32(&{cursor})"),
        TypeRef::U64 => format!("try Bincode.readVarintU64(&{cursor})"),
        TypeRef::I64 => format!("try Bincode.readVarintI64(&{cursor})"),
        TypeRef::F32 => format!("try Bincode.readF32(&{cursor})"),
        TypeRef::F64 => format!("try Bincode.readF64(&{cursor})"),
        TypeRef::String => format!("try Bincode.readString(&{cursor})"),
        TypeRef::Bytes => format!("try Bincode.readData(&{cursor})"),
        TypeRef::Vec(inner) => {
            let inner_reader = read_expr(inner, "$0");
            format!("try Bincode.readVec(&{cursor}) {{ {inner_reader} }}")
        }
        TypeRef::Option(inner) => {
            let inner_reader = read_expr(inner, "$0");
            format!("try Bincode.readOption(&{cursor}) {{ {inner_reader} }}")
        }
        TypeRef::Unit => "()".to_owned(),
        TypeRef::Named(name) => format!("try codecs.read{name}(&{cursor})"),
    }
}

fn write_write_expr(out: &mut String, indent: &str, ty: &TypeRef, binding: &str, buf: &str) {
    match ty {
        TypeRef::Named(name) => {
            let _ = writeln!(out, "{indent}codecs.write{name}(&{buf}, {binding})");
        }
        TypeRef::String => {
            let _ = writeln!(out, "{indent}Bincode.writeString(&{buf}, {binding})");
        }
        TypeRef::Bool => {
            let _ = writeln!(out, "{indent}Bincode.writeBool(&{buf}, {binding})");
        }
        TypeRef::U8 => {
            let _ = writeln!(out, "{indent}Bincode.writeU8(&{buf}, {binding})");
        }
        TypeRef::I8 => {
            let _ = writeln!(out, "{indent}Bincode.writeU8(&{buf}, UInt8(bitPattern: {binding}))");
        }
        TypeRef::U16 | TypeRef::U32 => {
            let _ = writeln!(out, "{indent}Bincode.writeVarintU32(&{buf}, UInt32({binding}))");
        }
        TypeRef::U64 => {
            let _ = writeln!(out, "{indent}Bincode.writeVarintU64(&{buf}, {binding})");
        }
        TypeRef::I16 | TypeRef::I32 => {
            let _ = writeln!(out, "{indent}Bincode.writeVarintI32(&{buf}, Int32({binding}))");
        }
        TypeRef::I64 => {
            let _ = writeln!(out, "{indent}Bincode.writeVarintI64(&{buf}, {binding})");
        }
        TypeRef::F32 => {
            let _ = writeln!(out, "{indent}Bincode.writeF32(&{buf}, {binding})");
        }
        TypeRef::F64 => {
            let _ = writeln!(out, "{indent}Bincode.writeF64(&{buf}, {binding})");
        }
        TypeRef::Bytes => {
            let _ = writeln!(out, "{indent}Bincode.writeData(&{buf}, {binding})");
        }
        TypeRef::Unit => {
            let _ = writeln!(out, "{indent}// () — nothing to encode");
        }
        TypeRef::Vec(inner) => {
            let closure = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVec(&{buf}, {binding}) {{ {closure} }}",
            );
        }
        TypeRef::Option(inner) => {
            let closure = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeOption(&{buf}, {binding}) {{ {closure} }}",
            );
        }
    }
}

fn write_lambda(ty: &TypeRef) -> String {
    // Closure param order: (inout Data, T) — `$0` is the buffer, `$1` is the
    // value. Using positional shorthand avoids the shadowing dance nested
    // closures otherwise trigger with `inout` capture.
    match ty {
        TypeRef::Named(name) => format!("codecs.write{name}(&$0, $1)"),
        TypeRef::String => "Bincode.writeString(&$0, $1)".to_owned(),
        TypeRef::Bool => "Bincode.writeBool(&$0, $1)".to_owned(),
        TypeRef::U8 => "Bincode.writeU8(&$0, $1)".to_owned(),
        TypeRef::I8 => "Bincode.writeU8(&$0, UInt8(bitPattern: $1))".to_owned(),
        TypeRef::U16 | TypeRef::U32 => "Bincode.writeVarintU32(&$0, UInt32($1))".to_owned(),
        TypeRef::U64 => "Bincode.writeVarintU64(&$0, $1)".to_owned(),
        TypeRef::I16 | TypeRef::I32 => "Bincode.writeVarintI32(&$0, Int32($1))".to_owned(),
        TypeRef::I64 => "Bincode.writeVarintI64(&$0, $1)".to_owned(),
        TypeRef::F32 => "Bincode.writeF32(&$0, $1)".to_owned(),
        TypeRef::F64 => "Bincode.writeF64(&$0, $1)".to_owned(),
        TypeRef::Bytes => "Bincode.writeData(&$0, $1)".to_owned(),
        TypeRef::Unit => "/* () */".to_owned(),
        TypeRef::Vec(inner) => {
            let closure = write_lambda(inner);
            format!("Bincode.writeVec(&$0, $1) {{ {closure} }}")
        }
        TypeRef::Option(inner) => {
            let closure = write_lambda(inner);
            format!("Bincode.writeOption(&$0, $1) {{ {closure} }}")
        }
    }
}
