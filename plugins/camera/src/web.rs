/// Browser host for the camera plugin. See the module docs for
/// pipeline details.
pub struct WebCamera {
    config: CameraInitConfig,
    // `SendWrapper` lets us carry `!Send` DOM handles through the
    // `Dispatch: Send + Sync + 'static` bound the runtime enforces.
    // Panics if accessed from a different OS thread — safe on
    // `wasm32-unknown-unknown`.
    sessions: SendWrapper<RefCell<HashMap<NativeHandleId, WebSessionEntry>>>,
    next_session: AtomicU64,
}

impl std::fmt::Debug for WebCamera {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("WebCamera")
            .field("config", &self.config)
            .field("session_count", &self.sessions.borrow().len())
            .finish_non_exhaustive()
    }
}

impl WebCamera {
    #[must_use]
    pub fn new(config: CameraInitConfig) -> Self {
        Self {
            config,
            sessions: SendWrapper::new(RefCell::new(HashMap::new())),
            next_session: AtomicU64::new(1),
        }
    }

    fn alloc_id(&self) -> NativeHandleId {
        NativeHandleId::new(self.next_session.fetch_add(1, Ordering::Relaxed))
    }

    fn pool_depth(&self) -> usize {
        let d = self.config.frame_pool_depth as usize;
        if d == 0 { 3 } else { d }
    }
}

impl Default for WebCamera {
    fn default() -> Self {
        Self::new(CameraInitConfig { frame_pool_depth: 3 })
    }
}

/// Live per-session state. Keeping the `Closure` + the interval
/// handle around is load-bearing — dropping the closure cancels the
/// callback the browser is holding.
struct WebSessionEntry {
    stream: MediaStream,
    video: HtmlVideoElement,
    canvas: HtmlCanvasElement,
    ctx: CanvasRenderingContext2d,
    interval_handle: i32,
    #[allow(dead_code)] // Must out-live the setInterval callback.
    pump: Closure<dyn FnMut()>,
    rx: flume::Receiver<CameraFrame>,
    pixel_format: PixelFormat,
    width: u32,
    height: u32,
}

impl Drop for WebSessionEntry {
    fn drop(&mut self) {
        if let Some(window) = web_sys::window() {
            window.clear_interval_with_handle(self.interval_handle);
        }
        stop_tracks(&self.stream);
        let _ = self.video.remove();
        let _ = self.canvas.remove();
    }
}

#[allow(clippy::missing_errors_doc)]
impl Camera for WebCamera {
    async fn devices(&self) -> Result<Vec<CameraDevice>, CameraError> {
        relay(|| enumerate_devices_impl()).await
    }

    async fn concurrent_support(&self) -> Result<ConcurrentSupport, CameraError> {
        Ok(ConcurrentSupport {
            max_concurrent: 4,
            approved_pairs: Vec::new(),
            any_combination: true,
        })
    }

    async fn access_status(&self) -> Result<AccessStatus, CameraError> {
        relay(|| access_status_impl()).await
    }

    async fn request_access(&self) -> Result<AccessStatus, CameraError> {
        relay(|| request_access_impl()).await
    }

    async fn open(&self, config: SessionConfig) -> Result<CameraSession, CameraError> {
        if !matches!(
            config.pixel_format,
            PixelFormat::Rgba8 | PixelFormat::Bgra8
        ) {
            return Err(CameraError::FormatUnsupported);
        }

        let pool_depth = self.pool_depth();
        let id = self.alloc_id();

        let built = relay(move || open_impl(id, pool_depth, config)).await?;
        self.sessions.borrow_mut().insert(id, built.entry.take());
        Ok(built.session)
    }

    async fn close(&self, session: NativeHandleId) -> Result<(), CameraError> {
        self.sessions.borrow_mut().remove(&session);
        Ok(())
    }

    fn frames(&self, session: NativeHandleId) -> flume::Receiver<CameraFrame> {
        self.sessions.borrow().get(&session).map_or_else(
            || {
                let (_tx, rx) = flume::bounded::<CameraFrame>(0);
                rx
            },
            |entry| entry.rx.clone(),
        )
    }

    async fn apply_controls(
        &self,
        session: NativeHandleId,
        controls: CameraControls,
    ) -> Result<AppliedControls, CameraError> {
        // Pull everything we need out of the session synchronously so
        // the spawned future doesn't need `&self` across `.await`.
        let track = {
            let sessions = self.sessions.borrow();
            let entry = sessions.get(&session).ok_or(CameraError::SessionClosed)?;
            SendWrapper::new(first_video_track(&entry.stream).ok_or_else(|| {
                CameraError::Backend("stream has no video track".into())
            })?)
        };

        relay(move || apply_controls_impl(track, controls)).await
    }

    async fn capture_still(
        &self,
        session: NativeHandleId,
        _request: StillCaptureRequest,
    ) -> Result<StillPhoto, CameraError> {
        let sessions = self.sessions.borrow();
        let entry = sessions.get(&session).ok_or(CameraError::SessionClosed)?;
        let bytes = read_frame(&entry.ctx, &entry.video, entry.width, entry.height)?;
        let mut bytes = bytes;
        if matches!(entry.pixel_format, PixelFormat::Bgra8) {
            swap_rb_in_place(&mut bytes);
        }
        Ok(StillPhoto {
            resolution: Resolution {
                width: entry.width,
                height: entry.height,
            },
            rotation_degrees: 0,
            pixel_format: entry.pixel_format,
            bytes,
            timestamp_ns: now_ns(),
        })
    }
}

