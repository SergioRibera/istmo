//! Android [`androidx.work.CoroutineWorker`] codegen.
//!
//! Emits a Kotlin [`androidx.work.CoroutineWorker`] subclass that decodes
//! its input `Data` blob (bincode-encoded `(String, String, Vec<u8>)`),
//! forwards it to the Rust adapter under the task's wire id, and maps the
//! returned [`crate::worker::WorkerContract`]-side `TaskOutcome` to
//! `WorkManager`'s `Result.success()` / `.retry()` / `.failure()`.
//!
//! No manifest entry is required — `WorkManager` registers
//! [`androidx.work.CoroutineWorker`] subclasses at runtime via the
//! [`androidx.work.WorkerFactory`].
//!
//! [`androidx.work.CoroutineWorker`]: https://developer.android.com/reference/androidx/work/CoroutineWorker
//! [`androidx.work.WorkerFactory`]: https://developer.android.com/reference/androidx/work/WorkerFactory

use std::fmt::Write as _;

/// Configuration for the Android side of a worker task.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct WorkerContract {
    /// Wire task id matching the Rust adapter's `PLUGIN_ID`.
    pub task_id: String,
    /// Kotlin class name for the generated `CoroutineWorker`.
    pub class_name: String,
    /// Kotlin package the worker class lives in.
    pub kotlin_package: String,
    /// Native library the `System.loadLibrary` call loads. Typically the
    /// cdylib name of the worker's Rust crate.
    pub lib_name: String,
    /// Package the `IstmoRuntime` singleton lives in.
    pub runtime_package: String,
}

impl WorkerContract {
    #[must_use]
    pub fn new(
        task_id: impl Into<String>,
        class_name: impl Into<String>,
        kotlin_package: impl Into<String>,
        lib_name: impl Into<String>,
    ) -> Self {
        Self {
            task_id: task_id.into(),
            class_name: class_name.into(),
            kotlin_package: kotlin_package.into(),
            lib_name: lib_name.into(),
            runtime_package: "dev.istmo.runtime".to_owned(),
        }
    }
}

/// Render the Kotlin `CoroutineWorker` subclass for `contract`.
#[must_use]
pub fn generate_android_worker(contract: &WorkerContract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// worker task id: {}", contract.task_id);
    let _ = writeln!(out);
    let _ = writeln!(out, "package {}", contract.kotlin_package);
    let _ = writeln!(out);
    let _ = writeln!(out, "import android.content.Context");
    let _ = writeln!(out, "import androidx.work.CoroutineWorker");
    let _ = writeln!(out, "import androidx.work.WorkerParameters");
    let _ = writeln!(out, "import {}.Bincode", contract.runtime_package);
    let _ = writeln!(out, "import {}.IstmoRuntime", contract.runtime_package);
    let _ = writeln!(out, "import java.io.ByteArrayOutputStream");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "class {}(context: Context, params: WorkerParameters)",
        contract.class_name,
    );
    let _ = writeln!(out, "    : CoroutineWorker(context, params) {{");
    let _ = writeln!(out);
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(
        out,
        "        const val TASK_ID: String = \"{}\"",
        contract.task_id
    );
    let _ = writeln!(
        out,
        "        private const val LIBRARY_NAME: String = \"{}\"",
        contract.lib_name,
    );
    let _ = writeln!(out, "        const val INPUT_KEY: String = \"istmo.input\"");
    let _ = writeln!(out);
    let _ = writeln!(out, "        init {{");
    let _ = writeln!(out, "            System.loadLibrary(LIBRARY_NAME)");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(out, "    override suspend fun doWork(): Result {{");
    let _ = writeln!(out, "        IstmoRuntime.start()");
    let _ = writeln!(
        out,
        "        val uniqueName = inputData.getString(\"istmo.unique_name\") ?: \"\""
    );
    let _ = writeln!(
        out,
        "        val input = inputData.getByteArray(INPUT_KEY) ?: ByteArray(0)"
    );
    let _ = writeln!(
        out,
        "        val payload = ByteArrayOutputStream().apply {{"
    );
    let _ = writeln!(out, "            Bincode.writeString(this, TASK_ID)");
    let _ = writeln!(out, "            Bincode.writeString(this, uniqueName)");
    let _ = writeln!(
        out,
        "            Bincode.writeVarintU64(this, input.size.toLong())"
    );
    let _ = writeln!(out, "            write(input)");
    let _ = writeln!(out, "        }}.toByteArray()");
    let _ = writeln!(
        out,
        "        val response = IstmoRuntime.call(TASK_ID, \"run\", payload)"
    );
    let _ = writeln!(
        out,
        "        return when (Bincode.readEnumDiscriminant(response, 0).value) {{"
    );
    let _ = writeln!(out, "            0 -> Result.success()");
    let _ = writeln!(out, "            1 -> Result.retry()");
    let _ = writeln!(out, "            else -> Result.failure()");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    out
}
