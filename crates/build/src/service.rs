use std::fmt::Write as _;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ServiceContract {
    pub plugin_id: String,

    pub class_name: String,

    pub kotlin_package: String,

    pub lib_name: String,

    pub runtime_package: String,

    pub foreground_service_type: Option<String>,

    pub exported: bool,

    pub permission: Option<String>,

    pub process: Option<String>,
}

impl ServiceContract {
    #[must_use]
    pub fn new(
        plugin_id: impl Into<String>,
        class_name: impl Into<String>,
        kotlin_package: impl Into<String>,
        lib_name: impl Into<String>,
    ) -> Self {
        Self {
            plugin_id: plugin_id.into(),
            class_name: class_name.into(),
            kotlin_package: kotlin_package.into(),
            lib_name: lib_name.into(),
            runtime_package: "dev.istmo.runtime".to_owned(),
            foreground_service_type: None,
            exported: false,
            permission: None,
            process: None,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AndroidServiceArtifacts {
    pub kotlin: String,

    pub manifest_fragment: String,
}

#[must_use]
pub fn generate_android_service(contract: &ServiceContract) -> AndroidServiceArtifacts {
    AndroidServiceArtifacts {
        kotlin: render_kotlin(contract),
        manifest_fragment: render_manifest(contract),
    }
}

fn render_kotlin(contract: &ServiceContract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// service plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
    let _ = writeln!(out, "package {}", contract.kotlin_package);
    let _ = writeln!(out);
    let _ = writeln!(out, "import android.content.Intent");
    let _ = writeln!(out, "import androidx.lifecycle.LifecycleService");
    let _ = writeln!(out, "import androidx.lifecycle.lifecycleScope");
    let _ = writeln!(out, "import {}.Bincode", contract.runtime_package);
    let _ = writeln!(out, "import {}.IstmoRuntime", contract.runtime_package);
    let _ = writeln!(out, "import kotlinx.coroutines.launch");
    let _ = writeln!(out);
    let _ = writeln!(out, "/**");
    let _ = writeln!(
        out,
        " * Generated `LifecycleService` shim for the istmo service plugin"
    );
    let _ = writeln!(out, " * `{}`.", contract.plugin_id);
    let _ = writeln!(out, " *");
    let _ = writeln!(
        out,
        " * Forwards `onStartCommand` and `onDestroy` into the Rust adapter"
    );
    let _ = writeln!(out, " * registered under the same plugin id.");
    let _ = writeln!(out, " */");
    let _ = writeln!(out, "class {} : LifecycleService() {{", contract.class_name);
    let _ = writeln!(out);
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(
        out,
        "        const val PLUGIN_ID: String = \"{}\"",
        contract.plugin_id
    );
    let _ = writeln!(
        out,
        "        private const val LIBRARY_NAME: String = \"{}\"",
        contract.lib_name,
    );
    let _ = writeln!(out);
    let _ = writeln!(out, "        init {{");
    let _ = writeln!(out, "            System.loadLibrary(LIBRARY_NAME)");
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(out, "    override fun onCreate() {{");
    let _ = writeln!(out, "        super.onCreate()");
    let _ = writeln!(out, "        IstmoRuntime.start()");
    let _ = writeln!(out, "        IstmoRuntime.registerService(PLUGIN_ID, this)");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(
        out,
        "    override fun onStartCommand(intent: Intent?, flags: Int, startId: Int): Int {{",
    );
    let _ = writeln!(out, "        super.onStartCommand(intent, flags, startId)");
    let _ = writeln!(out, "        val payload = Bincode.writeString(PLUGIN_ID)");
    let _ = writeln!(out, "        lifecycleScope.launch {{");
    let _ = writeln!(
        out,
        "            IstmoRuntime.call(PLUGIN_ID, \"on_start\", payload)"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "        return START_STICKY");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out);
    let _ = writeln!(out, "    override fun onDestroy() {{");
    let _ = writeln!(out, "        val payload = ByteArray(0)");
    let _ = writeln!(out, "        lifecycleScope.launch {{");
    let _ = writeln!(
        out,
        "            IstmoRuntime.call(PLUGIN_ID, \"on_stop\", payload)"
    );
    let _ = writeln!(out, "        }}");
    let _ = writeln!(out, "        IstmoRuntime.unregisterService(PLUGIN_ID)");
    let _ = writeln!(out, "        super.onDestroy()");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "}}");
    out
}

fn render_manifest(contract: &ServiceContract) -> String {
    let mut out = String::new();
    let _ = writeln!(out, "<!-- GENERATED by istmo-build - DO NOT EDIT. -->");
    let _ = writeln!(out, "<!-- service plugin id: {} -->", contract.plugin_id);
    let fq_name = format!("{}.{}", contract.kotlin_package, contract.class_name);
    let mut attrs: Vec<(String, String)> = Vec::new();
    attrs.push(("android:name".to_owned(), fq_name));
    attrs.push((
        "android:exported".to_owned(),
        if contract.exported { "true" } else { "false" }.to_owned(),
    ));
    if let Some(kind) = &contract.foreground_service_type {
        attrs.push(("android:foregroundServiceType".to_owned(), kind.clone()));
    }
    if let Some(permission) = &contract.permission {
        attrs.push(("android:permission".to_owned(), permission.clone()));
    }
    if let Some(process) = &contract.process {
        attrs.push(("android:process".to_owned(), process.clone()));
    }
    let _ = writeln!(out, "<service");
    for (i, (name, value)) in attrs.iter().enumerate() {
        let terminator = if i + 1 == attrs.len() { " />" } else { "" };
        let _ = writeln!(
            out,
            "    {name}=\"{value}\"{terminator}",
            name = name,
            value = xml_escape(value),
        );
    }
    out
}

fn xml_escape(value: &str) -> String {
    let mut out = String::with_capacity(value.len());
    for ch in value.chars() {
        match ch {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            other => out.push(other),
        }
    }
    out
}
