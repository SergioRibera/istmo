use std::fmt::Write as _;

use crate::contract::{Contract, Method, MethodKind, TypeRef};

#[must_use]
pub fn generate_kotlin_client(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    let _ = writeln!(out, "import java.io.ByteArrayOutputStream");
    if has_stream_method(contract) {
        let _ = writeln!(out, "import kotlinx.coroutines.flow.map");
    }
    let _ = writeln!(out);
    let name = &contract.type_name;
    let uses_codecs = uses_codecs(contract);
    let _ = writeln!(
        out,
        "/// Rust-hosted `{name}` plugin. Ships each call across the frame",
    );
    let _ = writeln!(out, "/// protocol via `IstmoRuntime.call(...)`.");
    if uses_codecs {
        let _ = writeln!(out, "class {name}Client(");
        let _ = writeln!(out, "    private val codecs: {name}Codecs,");
        let _ = writeln!(out, ") {{");
    } else {
        let _ = writeln!(out, "class {name}Client {{");
    }
    let _ = writeln!(out);
    let _ = writeln!(out, "    companion object {{");
    let _ = writeln!(
        out,
        "        const val PLUGIN_ID = \"{}\"",
        contract.plugin_id,
    );
    let _ = writeln!(out, "    }}");
    for method in &contract.methods {
        let _ = writeln!(out);
        write_client_method(&mut out, name, method);
    }
    let _ = writeln!(out, "}}");
    if let Some(err_ty) = domain_error(contract) {
        let _ = writeln!(out);
        let _ = writeln!(
            out,
            "/// Kotlin-side view of a domain error decoded from `Frame::Respond {{ Err(bytes) }}`.",
        );
        let _ = writeln!(out, "class {name}Exception(");
        let _ = writeln!(out, "    val payload: ByteArray,");
        let _ = writeln!(out, "    val decoded: {err_ty}?,");
        let _ = writeln!(out, ") : RuntimeException()");
    }
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
}

fn write_client_method(out: &mut String, plugin_ty: &str, method: &Method) {
    let arg_sig = format_args(method);
    let ret_kt = method.returns.to_kotlin();
    let has_error = method.error.is_some();
    match method.kind {
        MethodKind::Unary => {
            let returns_unit = matches!(method.returns, TypeRef::Unit);
            let sig_ret = if returns_unit {
                String::new()
            } else {
                format!(": {ret_kt}")
            };
            let _ = writeln!(
                out,
                "    suspend fun {}({arg_sig}){sig_ret} {{",
                method.name,
            );
            write_payload_build(out, method, "        ");
            let assign = if returns_unit { "" } else { "val bytes = " };
            if has_error {
                let err_ty = method.error.as_ref().unwrap().to_kotlin();
                let _ = writeln!(out, "        {assign}try {{");
                let _ = writeln!(
                    out,
                    "            IstmoRuntime.call(PLUGIN_ID, \"{}\", payload)",
                    method.name,
                );
                let _ = writeln!(out, "        }} catch (e: PluginException) {{");
                let _ = writeln!(
                    out,
                    "            val decoded = runCatching {{ codecs.read{err_ty}(e.payload, 0).value }}.getOrNull()",
                );
                let _ = writeln!(
                    out,
                    "            throw {plugin_ty}Exception(e.payload, decoded)",
                );
                let _ = writeln!(out, "        }}");
            } else {
                let _ = writeln!(
                    out,
                    "        {assign}IstmoRuntime.call(PLUGIN_ID, \"{}\", payload)",
                    method.name,
                );
            }
            if !returns_unit {
                write_return_decode(out, &method.returns, "        ");
            }
            let _ = writeln!(out, "    }}");
        }
        MethodKind::Stream => {

            let _ = writeln!(
                out,
                "    fun {}({arg_sig}): kotlinx.coroutines.flow.Flow<{ret_kt}> {{",
                method.name,
            );
            write_payload_build(out, method, "        ");
            let _ = writeln!(
                out,
                "        return IstmoRuntime.stream(PLUGIN_ID, \"{}\", payload).map {{ bytes ->",
                method.name,
            );
            write_stream_map_body(out, &method.returns, "            ");
            let _ = writeln!(out, "        }}");
            let _ = writeln!(out, "    }}");
        }
    }
}

fn write_payload_build(out: &mut String, method: &Method, indent: &str) {
    if method.args.is_empty() {
        let _ = writeln!(out, "{indent}val payload = ByteArray(0)");
        return;
    }
    let _ = writeln!(out, "{indent}val payloadBuf = ByteArrayOutputStream()");
    for arg in &method.args {
        write_write_expr(out, indent, &arg.ty, &arg.name, "payloadBuf");
    }
    let _ = writeln!(out, "{indent}val payload = payloadBuf.toByteArray()");
}

fn write_return_decode(out: &mut String, ret: &TypeRef, indent: &str) {
    let _ = writeln!(out, "{indent}var cursor = 0");
    write_read_expr(out, indent, ret, "result");
    let _ = writeln!(out, "{indent}return result");
}

fn write_stream_map_body(out: &mut String, ret: &TypeRef, indent: &str) {
    if matches!(ret, TypeRef::Unit) {
        let _ = writeln!(out, "{indent}Unit");
        return;
    }
    let _ = writeln!(out, "{indent}var cursor = 0");
    write_read_expr(out, indent, ret, "item");
    let _ = writeln!(out, "{indent}item");
}

fn format_args(method: &Method) -> String {
    method
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.ty.to_kotlin()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn uses_codecs(contract: &Contract) -> bool {
    contract.methods.iter().any(method_touches_named)
}

fn has_stream_method(contract: &Contract) -> bool {
    contract
        .methods
        .iter()
        .any(|m| matches!(m.kind, MethodKind::Stream))
}

fn method_touches_named(method: &Method) -> bool {
    method.args.iter().any(|a| ty_touches_named(&a.ty))
        || ty_touches_named(&method.returns)
        || method.error.as_ref().is_some_and(ty_touches_named)
}

fn ty_touches_named(ty: &TypeRef) -> bool {
    match ty {
        TypeRef::Named(_) => true,
        TypeRef::Vec(inner) | TypeRef::Option(inner) => ty_touches_named(inner),
        _ => false,
    }
}

fn domain_error(contract: &Contract) -> Option<String> {
    contract
        .methods
        .iter()
        .find_map(|m| m.error.as_ref().map(TypeRef::to_kotlin))
}

fn write_read_expr(out: &mut String, indent: &str, ty: &TypeRef, binding: &str) {
    if let TypeRef::Named(name) = ty {
        let _ = writeln!(
            out,
            "{indent}val d_{binding} = codecs.read{name}(bytes, cursor); cursor = d_{binding}.consumed",
        );
    } else {
        let reader = read_expr(ty, "bytes", "cursor");
        let _ = writeln!(
            out,
            "{indent}val d_{binding} = {reader}; cursor = d_{binding}.consumed",
        );
    }
    let _ = writeln!(out, "{indent}val {binding} = d_{binding}.value");
}

fn read_expr(ty: &TypeRef, bytes: &str, cursor: &str) -> String {
    match ty {
        TypeRef::Bool => format!("Bincode.readBool({bytes}, {cursor})"),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let cast = kt_int_cast(ty);
            format!(
                "Bincode.readVarintU64({bytes}, {cursor}).let {{ Bincode.Decoded(it.value{cast}, it.consumed) }}"
            )
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let cast = kt_int_cast(ty);
            format!(
                "Bincode.readVarintI64({bytes}, {cursor}).let {{ Bincode.Decoded(it.value{cast}, it.consumed) }}"
            )
        }
        TypeRef::F32 => format!("Bincode.readF32({bytes}, {cursor})"),
        TypeRef::F64 => format!("Bincode.readF64({bytes}, {cursor})"),
        TypeRef::String => format!("Bincode.readString({bytes}, {cursor})"),
        TypeRef::Bytes => format!("Bincode.readBytes({bytes}, {cursor})"),
        TypeRef::Vec(inner) => {
            let inner_reader = read_expr(inner, "p", "o");
            format!("Bincode.readVec({bytes}, {cursor}) {{ p, o -> {inner_reader} }}")
        }
        TypeRef::Option(inner) => {
            let inner_reader = read_expr(inner, "p", "o");
            format!("Bincode.readOption({bytes}, {cursor}) {{ p, o -> {inner_reader} }}")
        }
        TypeRef::Unit => format!("Bincode.Decoded(Unit, {cursor})"),
        TypeRef::Named(name) => format!("codecs.read{name}({bytes}, {cursor})"),
    }
}

fn write_write_expr(out: &mut String, indent: &str, ty: &TypeRef, binding: &str, buf: &str) {
    match ty {
        TypeRef::Named(name) => {
            let _ = writeln!(out, "{indent}codecs.write{name}({buf}, {binding})");
        }
        TypeRef::String => {
            let _ = writeln!(out, "{indent}Bincode.writeString({buf}, {binding})");
        }
        TypeRef::Bool => {
            let _ = writeln!(out, "{indent}Bincode.writeBool({buf}, {binding})");
        }
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVarintU64({buf}, {binding}.toLong())",
            );
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVarintI64({buf}, {binding}.toLong())",
            );
        }
        TypeRef::F32 => {
            let _ = writeln!(out, "{indent}Bincode.writeF32({buf}, {binding})");
        }
        TypeRef::F64 => {
            let _ = writeln!(out, "{indent}Bincode.writeF64({buf}, {binding})");
        }
        TypeRef::Bytes => {
            let _ = writeln!(out, "{indent}Bincode.writeBytes({buf}, {binding})");
        }
        TypeRef::Unit => {
            let _ = writeln!(out, "{indent}// () — nothing to encode");
        }
        TypeRef::Vec(inner) => {
            let inner_writer = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeVec({buf}, {binding}) {{ s, v -> {inner_writer} }}",
            );
        }
        TypeRef::Option(inner) => {
            let inner_writer = write_lambda(inner);
            let _ = writeln!(
                out,
                "{indent}Bincode.writeOption({buf}, {binding}) {{ s, v -> {inner_writer} }}",
            );
        }
    }
}

fn write_lambda(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Named(name) => format!("codecs.write{name}(s, v)"),
        TypeRef::String => "Bincode.writeString(s, v)".to_owned(),
        TypeRef::Bool => "Bincode.writeBool(s, v)".to_owned(),
        TypeRef::U8 | TypeRef::U16 | TypeRef::U32 | TypeRef::U64 => {
            "Bincode.writeVarintU64(s, v.toLong())".to_owned()
        }
        TypeRef::I8 | TypeRef::I16 | TypeRef::I32 | TypeRef::I64 => {
            "Bincode.writeVarintI64(s, v.toLong())".to_owned()
        }
        TypeRef::F32 => "Bincode.writeF32(s, v)".to_owned(),
        TypeRef::F64 => "Bincode.writeF64(s, v)".to_owned(),
        TypeRef::Bytes => "Bincode.writeBytes(s, v)".to_owned(),
        TypeRef::Unit => "/* () */".to_owned(),
        TypeRef::Vec(inner) => {
            let inner_writer = write_lambda(inner);
            format!("Bincode.writeVec(s, v) {{ ss, vv -> {inner_writer} }}")
        }
        TypeRef::Option(inner) => {
            let inner_writer = write_lambda(inner);
            format!("Bincode.writeOption(s, v) {{ ss, vv -> {inner_writer} }}")
        }
    }
}

const fn kt_int_cast(ty: &TypeRef) -> &'static str {
    match ty {
        TypeRef::U8 => ".toUByte()",
        TypeRef::U16 => ".toUShort()",
        TypeRef::U32 => ".toUInt()",
        TypeRef::U64 => ".toULong()",
        TypeRef::I8 => ".toByte()",
        TypeRef::I16 => ".toShort()",
        TypeRef::I32 => ".toInt()",
        _ => "",
    }
}

