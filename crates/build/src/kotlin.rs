//! Kotlin `interface` generator.
//!
//! Emits the declarative surface of a plugin trait — the interface itself
//! plus, for plugins that use `acquire_with`, a companion factory hook that
//! creates the native instance. The concrete implementation class (the one
//! that actually calls the istmo runtime) lands in a later milestone when
//! the runtime bindings for Kotlin are wired up.

use std::fmt::Write as _;

use crate::contract::{Contract, Method, MethodKind};

/// Renders the Kotlin surface for `contract`.
///
/// The output contains no `package` header or imports; wrapping is left to
/// the integration layer that consumes the generator.
#[must_use]
pub fn generate_kotlin(contract: &Contract) -> String {
    let mut out = String::new();
    write_header(&mut out, contract);
    write_interface(&mut out, contract);
    if let Some(init) = &contract.init {
        write_factory(&mut out, contract, init);
    }
    out
}

fn write_header(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "// GENERATED by istmo-build - DO NOT EDIT.");
    let _ = writeln!(out, "// plugin id: {}", contract.plugin_id);
    let _ = writeln!(out);
}

fn write_interface(out: &mut String, contract: &Contract) {
    let _ = writeln!(out, "interface {} {{", contract.type_name);
    for (i, method) in contract.methods.iter().enumerate() {
        if i > 0 {
            let _ = writeln!(out);
        }
        write_method(out, method);
    }
    let _ = writeln!(out, "}}");
}

fn write_method(out: &mut String, method: &Method) {
    let args = format_args(method);
    match method.kind {
        MethodKind::Unary => {
            let _ = writeln!(
                out,
                "    suspend fun {}({}): {}",
                method.name,
                args,
                method.returns.to_kotlin(),
            );
        }
        MethodKind::Stream => {
            let _ = writeln!(
                out,
                "    fun {}({}): kotlinx.coroutines.flow.Flow<{}>",
                method.name,
                args,
                method.returns.to_kotlin(),
            );
        }
    }
}

fn format_args(method: &Method) -> String {
    method
        .args
        .iter()
        .map(|a| format!("{}: {}", a.name, a.ty.to_kotlin()))
        .collect::<Vec<_>>()
        .join(", ")
}

fn write_factory(out: &mut String, contract: &Contract, init: &crate::contract::TypeRef) {
    let _ = writeln!(out);
    let _ = writeln!(out, "// Factory contract for `acquire_with`.");
    let _ = writeln!(out, "interface {}Factory {{", contract.type_name);
    let _ = writeln!(
        out,
        "    suspend fun create(config: {}): {}",
        init.to_kotlin(),
        contract.type_name,
    );
    let _ = writeln!(out, "}}");
}
